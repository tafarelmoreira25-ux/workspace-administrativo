create table if not exists public.funcionarios (
  id bigint generated by default as identity primary key,
  nome text not null,
  email text not null unique,
  cargo text,
  pontos integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.tarefas (
  id bigint generated by default as identity primary key,
  titulo text not null,
  descricao text,
  funcionaria_id bigint not null references public.funcionarios(id),
  pontos_tarefa integer not null default 10,
  data_limite date,
  status text not null default 'pendente',
  created_at timestamptz not null default now(),
  concluida_em timestamptz
);

alter table public.tarefas
  add column if not exists concluida_em timestamptz;

create table if not exists public.feedbacks (
  id bigint generated by default as identity primary key,
  funcionaria_id bigint not null references public.funcionarios(id),
  mensagem text not null,
  tipo text not null default 'positivo',
  created_at timestamptz not null default now()
);

create table if not exists public.planner_diario (
  id bigint generated by default as identity primary key,
  funcionaria_id bigint not null references public.funcionarios(id),
  categoria text not null,
  conteudo text not null,
  concluido boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.usuario_e_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select lower(coalesce(auth.jwt() ->> 'email', '')) = 'tafarel@platino.com';
$$;

create or replace function public.funcionario_id_autenticado()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id::bigint
  from public.funcionarios
  where lower(email) = lower(auth.jwt() ->> 'email')
  limit 1;
$$;

revoke all on function public.usuario_e_admin() from public;
revoke all on function public.funcionario_id_autenticado() from public;
grant execute on function public.usuario_e_admin() to authenticated;
grant execute on function public.funcionario_id_autenticado() to authenticated;

alter table public.funcionarios enable row level security;
alter table public.tarefas enable row level security;
alter table public.feedbacks enable row level security;
alter table public.planner_diario enable row level security;

revoke all on public.funcionarios from anon;
revoke all on public.tarefas from anon;
revoke all on public.feedbacks from anon;
revoke all on public.planner_diario from anon;

grant select on public.funcionarios to authenticated;
grant update (pontos) on public.funcionarios to authenticated;
grant select, insert, delete on public.tarefas to authenticated;
grant update (status) on public.tarefas to authenticated;
grant select, insert on public.feedbacks to authenticated;
grant select, insert, update, delete on public.planner_diario to authenticated;
grant usage, select on all sequences in schema public to authenticated;

