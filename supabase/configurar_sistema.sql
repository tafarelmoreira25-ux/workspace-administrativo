create table if not exists public.funcionarios (
  id bigint generated by default as identity primary key,
  nome text not null,
  email text not null unique,
  cargo text,
  created_at timestamptz not null default now()
);

create table if not exists public.feedbacks (
  id bigint generated by default as identity primary key,
  funcionaria_id bigint not null references public.funcionarios(id),
  mensagem text not null,
  tipo text not null default 'positivo',
  created_at timestamptz not null default now()
);

create table if not exists public.planner_diario (
  id bigint generated by default as identity primary key,
  funcionaria_id bigint not null references public.funcionarios(id),
  categoria text not null,
  conteudo text not null,
  concluido boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.usuario_e_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select lower(coalesce(auth.jwt() ->> 'email', '')) = 'tafarel@platino.com';
$$;

create or replace function public.funcionario_id_autenticado()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id::bigint
  from public.funcionarios
  where lower(trim(email)) =
    lower(trim(coalesce(auth.jwt() ->> 'email', '')))
  limit 1;
$$;

create or replace function public.feedback_pertence_ao_usuario(
  p_funcionaria_id bigint
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.funcionarios funcionario
    where funcionario.id = p_funcionaria_id
      and lower(trim(funcionario.email)) =
        lower(trim(coalesce(auth.jwt() ->> 'email', '')))
  );
$$;

revoke all on function public.usuario_e_admin() from public;
revoke all on function public.funcionario_id_autenticado() from public;
revoke all on function public.feedback_pertence_ao_usuario(bigint) from public;
grant execute on function public.usuario_e_admin() to authenticated;
grant execute on function public.funcionario_id_autenticado() to authenticated;
grant execute on function public.feedback_pertence_ao_usuario(bigint)
  to authenticated;

alter table public.funcionarios enable row level security;
revoke all on public.funcionarios from anon;
alter table public.feedbacks enable row level security;
revoke all on public.feedbacks from anon;
alter table public.planner_diario enable row level security;
revoke all on public.planner_diario from anon;

grant select on public.funcionarios to authenticated;
grant select, insert on public.feedbacks to authenticated;
grant select, insert, update, delete on public.planner_diario to authenticated;
grant usage, select on all sequences in schema public to authenticated;
drop policy if exists "Equipe consulta funcionarios" on public.funcionarios;
create policy "Equipe consulta funcionarios"
on public.funcionarios for select to authenticated
using (
  public.usuario_e_admin()
  or public.funcionario_id_autenticado() is not null
);

drop policy if exists "Equipe consulta feedbacks permitidos" on public.feedbacks;
drop policy if exists "Funcionaria consulta feedbacks recebidos"
on public.feedbacks;
create policy "Funcionaria consulta feedbacks recebidos"
on public.feedbacks for select to authenticated
using (
  public.usuario_e_admin()
  or public.feedback_pertence_ao_usuario(funcionaria_id)
);

drop policy if exists "Supervisor registra feedbacks" on public.feedbacks;
create policy "Supervisor registra feedbacks"
on public.feedbacks for insert to authenticated
with check (public.usuario_e_admin());

drop policy if exists "Funcionaria consulta proprio planner" on public.planner_diario;
create policy "Funcionaria consulta proprio planner"
on public.planner_diario for select to authenticated
using (funcionaria_id = public.funcionario_id_autenticado());

drop policy if exists "Funcionaria cria no proprio planner" on public.planner_diario;
create policy "Funcionaria cria no proprio planner"
on public.planner_diario for insert to authenticated
with check (funcionaria_id = public.funcionario_id_autenticado());

drop policy if exists "Funcionaria atualiza proprio planner" on public.planner_diario;
create policy "Funcionaria atualiza proprio planner"
on public.planner_diario for update to authenticated
using (funcionaria_id = public.funcionario_id_autenticado())
with check (funcionaria_id = public.funcionario_id_autenticado());

drop policy if exists "Funcionaria exclui do proprio planner" on public.planner_diario;
create policy "Funcionaria exclui do proprio planner"
on public.planner_diario for delete to authenticated
using (funcionaria_id = public.funcionario_id_autenticado());
