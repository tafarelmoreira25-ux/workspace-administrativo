create or replace function public.usuario_e_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select lower(coalesce(auth.jwt() ->> 'email', '')) = 'tafarel@platino.com';
$$;

create or replace function public.funcionario_id_autenticado()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id::bigint
  from public.funcionarios
  where lower(trim(email)) =
    lower(trim(coalesce(auth.jwt() ->> 'email', '')))
  limit 1;
$$;

create or replace function public.feedback_pertence_ao_usuario(
  p_funcionaria_id bigint
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.funcionarios funcionario
    where funcionario.id = p_funcionaria_id
      and lower(trim(funcionario.email)) =
        lower(trim(coalesce(auth.jwt() ->> 'email', '')))
  );
$$;

revoke all on function public.usuario_e_admin() from public;
