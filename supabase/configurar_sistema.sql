create table if not exists public.funcionarios (
  id bigint generated by default as identity primary key,
  nome text not null,
  email text not null unique,
  cargo text,
  pontos integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.tarefas (
  id bigint generated by default as identity primary key,
  titulo text not null,
  descricao text,
  funcionaria_id bigint not null references public.funcionarios(id),
  pontos_tarefa integer not null default 10,
  data_limite date,
  status text not null default 'pendente',
  created_at timestamptz not null default now(),
  concluida_em timestamptz,
  prioridade text not null default 'normal',
  apontamento text,
  exibir_tv boolean not null default true,
  updated_at timestamptz not null default now()
);

alter table public.tarefas
  add column if not exists concluida_em timestamptz,
  add column if not exists prioridade text not null default 'normal',
  add column if not exists apontamento text,
  add column if not exists exibir_tv boolean not null default true,
  add column if not exists updated_at timestamptz not null default now();

do $$
declare
  restricao record;
begin
  for restricao in
    select conname
    from pg_constraint
    where conrelid = 'public.tarefas'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%status%'
  loop
    execute format(
      'alter table public.tarefas drop constraint %I',
      restricao.conname
    );
  end loop;
end;
$$;

alter table public.tarefas
  add constraint tarefas_status_check
  check (
    status in ('pendente', 'concluida', 'responsabilidade_mensal')
  );

alter table public.tarefas
  drop constraint if exists tarefas_prioridade_check;

alter table public.tarefas
  add constraint tarefas_prioridade_check
  check (prioridade in ('normal', 'alta', 'urgente'));

create index if not exists tarefas_responsabilidades_mensais_idx
on public.tarefas (funcionaria_id, data_limite, id)
where status = 'responsabilidade_mensal';

create index if not exists tarefas_painel_tv_idx
on public.tarefas (exibir_tv, status, prioridade, data_limite);

create table if not exists public.feedbacks (
  id bigint generated by default as identity primary key,
  funcionaria_id bigint not null references public.funcionarios(id),
  mensagem text not null,
