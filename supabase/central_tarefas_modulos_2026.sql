create or replace function public.auditar_alteracao_prazo()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if new.prazo_limite is distinct from old.prazo_limite then
    insert into public.tarefas_prazos_historico(tarefa_id,prazo_anterior,prazo_novo,motivo)
    values(new.id,old.prazo_limite,new.prazo_limite,'Prazo alterado no sistema.');
    perform public.registrar_evento_tarefa(new.id,'prazo_alterado',old.status,new.status,'Prazo da tarefa alterado.',jsonb_build_object('prazo_anterior',old.prazo_limite,'prazo_novo',new.prazo_limite));
  end if;
  return new;
end $$;
