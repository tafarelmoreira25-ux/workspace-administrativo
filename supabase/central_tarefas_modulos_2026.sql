create or replace function public.criar_urgencia(
  p_nome_cliente text,p_cpf_ou_id text,p_setor text,p_funcionaria_id bigint,
  p_tarefa text,p_motivo text,p_prazo timestamptz,p_prioridade text,
  p_observacao text default null,p_drive_url text default null
) returns public.urgencias language plpgsql security definer set search_path=public as $$
declare u public.urgencias; cliente_final bigint; email_resp text; codigo_final text;
begin
  if not public.usuario_e_admin() and public.funcionario_id_autenticado() is null then raise exception 'Usuario da equipe nao identificado.'; end if;
  if nullif(trim(p_nome_cliente),'') is null or nullif(trim(p_tarefa),'') is null or nullif(trim(p_motivo),'') is null then raise exception 'Cliente, tarefa e motivo sao obrigatorios.'; end if;
  if p_prazo is null or p_prazo<=now() then raise exception 'Prazo futuro obrigatorio.'; end if;
  if p_prioridade not in ('alta','urgente','critica') then raise exception 'Prioridade invalida.'; end if;
  select id into cliente_final from public.clientes where lower(trim(nome))=lower(trim(p_nome_cliente)) and ativo order by id desc limit 1;
  if cliente_final is null then
    perform pg_advisory_xact_lock(hashtext('cliente-operacional'));
    insert into public.clientes(codigo_interno,nome,cpf)
    values('CLI-'||to_char(current_date,'YYYYMMDD')||'-'||lpad((select (count(*)+1)::text from public.clientes where created_at::date=current_date),3,'0'),trim(p_nome_cliente),nullif(trim(p_cpf_ou_id),'')) returning id into cliente_final;
  end if;
  perform pg_advisory_xact_lock(hashtext('urgencia-'||to_char(current_date,'YYYYMMDD')));
  codigo_final:='URG-'||to_char(current_date,'YYYYMMDD')||'-'||lpad((select (count(*)+1)::text from public.urgencias where created_at::date=current_date),3,'0');
  insert into public.urgencias(codigo,cliente_id,nome_cliente,cpf_ou_id,setor_responsavel,funcionaria_id,tarefa_necessaria,motivo,prazo_limite,prioridade,observacao,drive_url)
  values(codigo_final,cliente_final,trim(p_nome_cliente),nullif(trim(p_cpf_ou_id),''),trim(p_setor),p_funcionaria_id,trim(p_tarefa),trim(p_motivo),p_prazo,p_prioridade,nullif(trim(p_observacao),''),nullif(trim(p_drive_url),'')) returning * into u;
  insert into public.urgencias_eventos(urgencia_id,evento,status_novo,descricao) values(u.id,'criada','aberta','Urgencia registrada.');
  if p_funcionaria_id is not null then select email into email_resp from public.funcionarios where id=p_funcionaria_id; end if;
  perform public.notificar_tarefa(null,p_funcionaria_id,email_resp,'nova_urgencia','Nova urgencia',u.codigo||' · '||u.nome_cliente||' · '||u.tarefa_necessaria);
  return u;
end $$;

create or replace function public.movimentar_urgencia(p_urgencia_id bigint,p_status text,p_observacao text default null)
returns public.urgencias language plpgsql security definer set search_path=public as $$
declare u public.urgencias; anterior text; uid bigint:=public.funcionario_id_autenticado();
begin
  select * into u from public.urgencias where id=p_urgencia_id for update;
  if u.id is null then raise exception 'Urgencia nao encontrada.'; end if;
  if not public.usuario_e_admin() and u.funcionaria_id is distinct from uid then raise exception 'Urgencia nao atribuida ao usuario.'; end if;
  if p_status not in ('visualizada','em_atendimento','encaminhada','resolvida','cancelada') then raise exception 'Status invalido.'; end if;
  anterior:=u.status;
  update public.urgencias set status=p_status,visualizada_em=case when p_status='visualizada' then now() else visualizada_em end,
    iniciada_em=case when p_status='em_atendimento' then coalesce(iniciada_em,now()) else iniciada_em end,
    resolvida_em=case when p_status='resolvida' then now() else resolvida_em end,observacao=coalesce(nullif(trim(p_observacao),''),observacao),updated_at=now()
  where id=u.id returning * into u;
  insert into public.urgencias_eventos(urgencia_id,evento,status_anterior,status_novo,descricao)
  values(u.id,'status_alterado',anterior,p_status,coalesce(nullif(trim(p_observacao),''),'Urgencia movimentada.'));
  return u;
end $$;

create or replace function public.enviar_chamada_atencao(p_tarefa_id bigint,p_nivel text,p_mensagem text,p_prazo_sugerido timestamptz default null,p_print_drive_url text default null)
returns public.chamadas_atencao language plpgsql security definer set search_path=public as $$
declare c public.chamadas_atencao; t public.tarefas; email_autor text:=lower(coalesce(auth.jwt()->>'email',''));
begin
  select * into t from public.tarefas where id=p_tarefa_id;
  if t.id is null then raise exception 'Tarefa nao encontrada.'; end if;
  if not public.usuario_e_admin() and lower(coalesce(t.solicitante_email,''))<>email_autor then raise exception 'Somente o solicitante ou supervisor pode chamar atencao.'; end if;
  insert into public.chamadas_atencao(tarefa_id,nivel,mensagem,prazo_sugerido,print_drive_url)
  values(p_tarefa_id,p_nivel,trim(p_mensagem),p_prazo_sugerido,nullif(trim(p_print_drive_url),'')) returning * into c;
  perform public.registrar_evento_tarefa(t.id,'chamada_atencao',t.status,t.status,'Chamada de atencao: '||trim(p_mensagem),jsonb_build_object('nivel',p_nivel));
  perform public.notificar_tarefa(t.id,t.funcionaria_id,null,'chamada_atencao','Chamada de atencao',trim(p_mensagem));
  return c;
end $$;

create or replace function public.marcar_notificacao_lida(p_notificacao_id bigint)
returns void language plpgsql security definer set search_path=public as $$
begin
  update public.notificacoes_operacionais set lida_em=now() where id=p_notificacao_id
    and (public.usuario_e_admin() or funcionaria_id=public.funcionario_id_autenticado() or destinatario_email=lower(coalesce(auth.jwt()->>'email','')));
end $$;

create or replace function public.listar_clientes_central()
returns setof public.clientes language sql stable security definer set search_path=public as $$
  select c.* from public.clientes c
  where public.usuario_e_admin() or public.funcionario_id_autenticado() is not null
  order by c.ultima_movimentacao desc,c.nome;
$$;

create or replace view public.central_dashboard with(security_invoker=true) as
select t.funcionaria_id,
  count(*) filter(where t.status not in ('concluida','cancelada','arquivada') and t.prazo_limite<now()) atrasadas,
  count(*) filter(where t.status not in ('concluida','cancelada','arquivada') and t.prazo_limite::date=current_date) vencem_hoje,
  count(*) filter(where t.status not in ('concluida','cancelada','arquivada') and t.prazo_limite>now() and t.prazo_limite<=now()+interval '48 hours') proximas,
  count(*) filter(where t.prioridade in ('urgente','critica') and t.status not in ('concluida','cancelada','arquivada')) urgentes,
  count(*) filter(where t.status in ('devolvida','devolvida_correcao')) devolvidas,
  count(*) filter(where t.status='delegada') recem_delegadas,
  count(*) filter(where t.status='em_execucao') em_andamento,
  count(*) filter(where t.status='concluida' and t.concluida_em>=now()-interval '7 days') concluidas_recentes
from public.tarefas t group by t.funcionaria_id;

