create or replace function public.salvar_processo_cliente(
  p_id bigint,
  p_numero_processo text,
  p_reu text,
  p_data_distribuicao date,
  p_tribunal text,
  p_comarca text,
  p_vara text,
  p_status_categoria text,
  p_status_original text,
  p_justica_gratuita text,
  p_emenda_inicial text,
  p_link_processo text,
  p_movimentacoes text,
  p_observacoes text,
  p_tratativas text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_numero text := public.normalizar_numero_processo(p_numero_processo);
  v_email text := lower(trim(coalesce(auth.jwt() ->> 'email', '')));
begin
  if not public.usuario_pode_editar_status_processual() then
    raise exception 'Somente o departamento Administrativo pode editar a carteira processual.';
  end if;
  if p_status_categoria is not null and p_status_categoria not in (
    'tramitando', 'arquivado', 'improcedente', 'procedente',
    'parcialmente_procedente', 'nao_confirmado', 'outro'
  ) then
    raise exception 'Categoria de status invalida.';
  end if;
  if not exists (select 1 from public.processos_clientes where id = p_id) then
    raise exception 'Processo nao encontrado.';
  end if;

  update public.processos_clientes
  set numero_processo = v_numero,
      numero_processo_normalizado = v_numero,
      reu = nullif(trim(coalesce(p_reu, '')), ''),
      data_distribuicao = p_data_distribuicao,
      tribunal = nullif(trim(coalesce(p_tribunal, '')), ''),
      comarca = nullif(trim(coalesce(p_comarca, '')), ''),
      vara = nullif(trim(coalesce(p_vara, '')), ''),
      status_categoria = p_status_categoria,
      status_original = nullif(trim(coalesce(p_status_original, '')), ''),
      justica_gratuita = nullif(trim(coalesce(p_justica_gratuita, '')), ''),
      emenda_inicial = nullif(trim(coalesce(p_emenda_inicial, '')), ''),
      link_processo = nullif(trim(coalesce(p_link_processo, '')), ''),
      movimentacoes = nullif(p_movimentacoes, ''),
      observacoes = nullif(p_observacoes, ''),
      tratativas = nullif(p_tratativas, ''),
      atualizado_por_email = v_email,
      updated_at = now()
  where id = p_id;
  return p_id;
end;
$$;

