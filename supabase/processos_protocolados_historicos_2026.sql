-- Carteira processual historica: um cliente pode possuir varios processos.
-- Migration aditiva e idempotente. Nao remove nem reclassifica dados existentes.

begin;

alter table public.clientes
  add column if not exists numero_processo text;

create or replace function public.normalizar_nome_importacao(p_valor text)
returns text
language sql
immutable
parallel safe
set search_path = public
as $$
  select nullif(
    translate(
      lower(regexp_replace(trim(coalesce(p_valor, '')), '\s+', ' ', 'g')),
      'áàâãäéèêëíìîïóòôõöúùûüç',
      'aaaaaeeeeiiiiooooouuuuc'
    ),
    ''
  );
$$;

create or replace function public.normalizar_numero_processo(p_valor text)
returns text
language sql
immutable
parallel safe
set search_path = public
as $$
  select nullif(
    trim(both '.' from regexp_replace(trim(coalesce(p_valor, '')), '\s+', '', 'g')),
    ''
  );
$$;

create table if not exists public.processos_clientes (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references public.clientes(id) on delete restrict,
  numero_processo text,
  numero_processo_normalizado text,
  reu text,
  data_distribuicao date,
  tribunal text,
  comarca text,
  vara text,
  status_categoria text check (status_categoria is null or status_categoria in (
    'tramitando', 'arquivado', 'improcedente', 'procedente',
    'parcialmente_procedente', 'nao_confirmado', 'outro'
  )),
  status_original text,
  justica_gratuita text,
  emenda_inicial text,
  link_processo text,
  movimentacoes text,
  observacoes text,
  tratativas text,
  fonte text,
  fonte_linha_provisoria integer,
  fontes_linhas integer[] not null default '{}'::integer[],
  criado_por_email text not null default lower(coalesce(auth.jwt() ->> 'email', 'sistema')),
  atualizado_por_email text not null default lower(coalesce(auth.jwt() ->> 'email', 'sistema')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  incompleto boolean generated always as (
    numero_processo_normalizado is null
    or data_distribuicao is null
    or status_categoria is null
    or status_categoria = 'nao_confirmado'
    or justica_gratuita is null
    or emenda_inicial is null
  ) stored,
  constraint processos_clientes_numero_consistente_check check (
    numero_processo_normalizado is not distinct from public.normalizar_numero_processo(numero_processo)
  ),
  constraint processos_clientes_provisorio_check check (
    numero_processo_normalizado is not null or fonte_linha_provisoria is not null
  )
);

-- Corrige apenas a declaracao caso a migration tenha sido interrompida antes do commit.
do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'processos_clientes'
      and column_name = 'fontes_linhas'
      and udt_name <> '_int4'
  ) then
    raise exception 'A coluna processos_clientes.fontes_linhas possui tipo inesperado.';
  end if;
end;
$$;

create unique index if not exists processos_clientes_numero_uidx
  on public.processos_clientes(numero_processo_normalizado)
  where numero_processo_normalizado is not null;

create unique index if not exists processos_clientes_provisorio_uidx
  on public.processos_clientes(fonte, fonte_linha_provisoria)
  where fonte_linha_provisoria is not null;

create index if not exists processos_clientes_cliente_idx
  on public.processos_clientes(cliente_id, updated_at desc);

create index if not exists processos_clientes_status_idx
  on public.processos_clientes(status_categoria, data_distribuicao desc nulls last);

create table if not exists public.importacoes_processos_protocolados_linhas (
  id bigint generated by default as identity primary key,
  fonte text not null,
  linha integer not null,
  cliente_id bigint references public.clientes(id) on delete set null,
  processo_id bigint references public.processos_clientes(id) on delete set null,
  acao_cliente text,
  acao_processo text,
  avisos jsonb not null default '[]'::jsonb,
  erro text,
  processado_em timestamptz not null default now(),
  unique (fonte, linha)
);

create or replace function public.importar_processos_protocolados_lote(
  p_lote jsonb,
  p_fonte text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  v_linha integer;
  v_nome text;
  v_nome_normalizado text;
  v_numero text;
  v_cliente public.clientes;
  v_processo public.processos_clientes;
  v_cliente_acao text;
  v_processo_acao text;
  v_avisos jsonb;
  v_resultados jsonb := '[]'::jsonb;
  v_email text := lower(trim(coalesce(auth.jwt() ->> 'email', 'importador')));
  v_linhas integer[];
  v_alterados integer;
begin
  if auth.role() <> 'service_role' and not public.usuario_pode_editar_status_processual() then
    raise exception 'Importacao restrita ao service_role ou ao departamento Administrativo.';
  end if;
  if jsonb_typeof(p_lote) <> 'array' then
    raise exception 'O lote deve ser um array JSON.';
  end if;
  if nullif(trim(coalesce(p_fonte, '')), '') is null then
    raise exception 'A fonte da importacao e obrigatoria.';
  end if;

  for item in select value from jsonb_array_elements(p_lote)
  loop
    v_linha := coalesce((item ->> 'linha')::integer, 0);
    v_nome := nullif(trim(item ->> 'autor'), '');
    v_nome_normalizado := public.normalizar_nome_importacao(v_nome);
    v_numero := public.normalizar_numero_processo(item ->> 'numero_processo');
    v_cliente_acao := null;
    v_processo_acao := null;
    v_avisos := '[]'::jsonb;

    begin
      if v_linha < 2 then
        raise exception 'Numero de linha invalido.';
      end if;
      if v_nome_normalizado is null then
        raise exception 'Cliente ausente.';
      end if;
      if v_nome_normalizado = public.normalizar_nome_importacao('Captura de tela') then
        raise exception 'Linha invalida/nao corresponde a cliente.';
      end if;

      v_processo := null;
      if v_numero is not null then
        select p.* into v_processo
        from public.processos_clientes p
        where p.numero_processo_normalizado = v_numero
        for update;
      end if;
      if v_processo.id is null then
        select p.* into v_processo
        from public.processos_clientes p
        where p.fonte = p_fonte
          and p.fonte_linha_provisoria = v_linha
        for update;
      end if;

      v_cliente := null;
      if v_processo.id is not null then
        select c.* into v_cliente from public.clientes c where c.id = v_processo.cliente_id;
        if public.normalizar_nome_importacao(v_cliente.nome) is distinct from v_nome_normalizado then
          if v_cliente.origem = 'importacao_processos_protocolados' then
            update public.clientes
            set nome = v_nome,
                identificador_origem = v_nome_normalizado,
                updated_at = now()
            where id = v_cliente.id
            returning * into v_cliente;
            v_avisos := v_avisos || jsonb_build_array(jsonb_build_object(
              'campo', 'autor',
              'motivo', 'Codificacao/nome do cliente criado pela importacao foi corrigido pela fonte.'
            ));
          else
            v_avisos := v_avisos || jsonb_build_array(jsonb_build_object(
              'campo', 'autor', 'banco', v_cliente.nome, 'fonte', v_nome,
              'motivo', 'Numero de processo ja vinculado a outro nome; vinculo existente preservado.'
            ));
          end if;
        end if;
      else
        select c.* into v_cliente
        from public.clientes c
        where public.normalizar_nome_importacao(c.nome) = v_nome_normalizado
        order by c.ativo desc nulls last, c.id
        limit 1;
      end if;

      if v_cliente.id is null then
        insert into public.clientes (
          codigo_interno, nome, origem, identificador_origem, ativo
        ) values (
          'CLI-IMP-PROC-' || upper(substr(md5(v_nome_normalizado), 1, 16)),
          v_nome,
          'importacao_processos_protocolados',
          v_nome_normalizado,
          true
        )
        returning * into v_cliente;
        v_cliente_acao := 'criado';
      else
        v_cliente_acao := 'reutilizado';
      end if;

      if v_processo.id is null then
        insert into public.processos_clientes (
          cliente_id, numero_processo, numero_processo_normalizado, reu,
          data_distribuicao, status_categoria, status_original,
          justica_gratuita, emenda_inicial, link_processo, observacoes,
          fonte, fonte_linha_provisoria, fontes_linhas,
          criado_por_email, atualizado_por_email
        ) values (
          v_cliente.id, v_numero, v_numero, nullif(trim(item ->> 'reu'), ''),
          (item ->> 'data_distribuicao')::date,
          nullif(trim(item ->> 'status_categoria'), ''),
          nullif(trim(item ->> 'status_original'), ''),
          nullif(trim(item ->> 'justica_gratuita'), ''),
          nullif(trim(item ->> 'emenda_inicial'), ''),
          nullif(trim(item ->> 'link_processo'), ''),
          case when nullif(item ->> 'observacoes', '') is null then null else item ->> 'observacoes' end,
          p_fonte,
          v_linha,
          array[v_linha],
          v_email, v_email
        )
        returning * into v_processo;
        v_processo_acao := 'criado';
      else
        v_linhas := case
          when v_linha = any(v_processo.fontes_linhas) then v_processo.fontes_linhas
          else array_append(v_processo.fontes_linhas, v_linha)
        end;

        update public.processos_clientes p
        set numero_processo = coalesce(v_numero, p.numero_processo),
            numero_processo_normalizado = coalesce(v_numero, p.numero_processo_normalizado),
            reu = coalesce(nullif(trim(item ->> 'reu'), ''), p.reu),
            data_distribuicao = coalesce((item ->> 'data_distribuicao')::date, p.data_distribuicao),
            status_categoria = coalesce(nullif(trim(item ->> 'status_categoria'), ''), p.status_categoria),
            status_original = coalesce(nullif(trim(item ->> 'status_original'), ''), p.status_original),
            justica_gratuita = coalesce(nullif(trim(item ->> 'justica_gratuita'), ''), p.justica_gratuita),
            emenda_inicial = coalesce(nullif(trim(item ->> 'emenda_inicial'), ''), p.emenda_inicial),
            link_processo = coalesce(nullif(trim(item ->> 'link_processo'), ''), p.link_processo),
            observacoes = coalesce(case when nullif(item ->> 'observacoes', '') is null then null else item ->> 'observacoes' end, p.observacoes),
            fonte = coalesce(p.fonte, p_fonte),
            fonte_linha_provisoria = coalesce(p.fonte_linha_provisoria, v_linha),
            fontes_linhas = v_linhas,
            atualizado_por_email = v_email,
            updated_at = now()
        where p.id = v_processo.id
          and row(
            p.numero_processo, p.numero_processo_normalizado, p.reu,
            p.data_distribuicao, p.status_categoria, p.status_original,
            p.justica_gratuita, p.emenda_inicial, p.link_processo,
            p.observacoes, p.fonte, p.fonte_linha_provisoria, p.fontes_linhas
          ) is distinct from row(
            coalesce(v_numero, p.numero_processo),
            coalesce(v_numero, p.numero_processo_normalizado),
            coalesce(nullif(trim(item ->> 'reu'), ''), p.reu),
            coalesce((item ->> 'data_distribuicao')::date, p.data_distribuicao),
            coalesce(nullif(trim(item ->> 'status_categoria'), ''), p.status_categoria),
            coalesce(nullif(trim(item ->> 'status_original'), ''), p.status_original),
            coalesce(nullif(trim(item ->> 'justica_gratuita'), ''), p.justica_gratuita),
            coalesce(nullif(trim(item ->> 'emenda_inicial'), ''), p.emenda_inicial),
            coalesce(nullif(trim(item ->> 'link_processo'), ''), p.link_processo),
            coalesce(case when nullif(item ->> 'observacoes', '') is null then null else item ->> 'observacoes' end, p.observacoes),
            coalesce(p.fonte, p_fonte),
            coalesce(p.fonte_linha_provisoria, v_linha),
            v_linhas
          );
        get diagnostics v_alterados = row_count;
        v_processo_acao := case when v_alterados > 0 then 'atualizado' else 'inalterado' end;
        select p.* into v_processo from public.processos_clientes p where p.id = v_processo.id;
      end if;

      -- Compatibilidade com telas antigas que exibem um unico numero no cliente.
      update public.clientes
      set numero_processo = v_numero, updated_at = now()
      where id = v_cliente.id
        and v_numero is not null
        and nullif(trim(coalesce(numero_processo, '')), '') is null;

      insert into public.importacoes_processos_protocolados_linhas (
        fonte, linha, cliente_id, processo_id, acao_cliente, acao_processo,
        avisos, erro, processado_em
      ) values (
        p_fonte, v_linha, v_cliente.id, v_processo.id, v_cliente_acao,
        v_processo_acao, v_avisos, null, now()
      )
      on conflict (fonte, linha) do update set
        cliente_id = excluded.cliente_id,
        processo_id = excluded.processo_id,
        acao_cliente = excluded.acao_cliente,
        acao_processo = excluded.acao_processo,
        avisos = excluded.avisos,
        erro = null,
        processado_em = now();

      v_resultados := v_resultados || jsonb_build_array(jsonb_build_object(
        'linha', v_linha,
        'cliente_id', v_cliente.id,
        'processo_id', v_processo.id,
        'cliente_acao', v_cliente_acao,
        'processo_acao', v_processo_acao,
        'incompleto', v_processo.incompleto,
        'avisos', v_avisos
      ));
    exception when others then
      insert into public.importacoes_processos_protocolados_linhas (
        fonte, linha, avisos, erro, processado_em
      ) values (p_fonte, v_linha, v_avisos, sqlerrm, now())
      on conflict (fonte, linha) do update set
        avisos = excluded.avisos,
        erro = excluded.erro,
        processado_em = now();

      v_resultados := v_resultados || jsonb_build_array(jsonb_build_object(
        'linha', v_linha, 'erro', sqlerrm, 'avisos', v_avisos
      ));
    end;
  end loop;

  return jsonb_build_object('resultados', v_resultados);
end;
$$;

create or replace function public.listar_processos_clientes()
returns table (
  id bigint,
  cliente_id bigint,
  nome_cliente text,
  numero_processo text,
  reu text,
  data_distribuicao date,
  tribunal text,
  comarca text,
  vara text,
  status_categoria text,
  status_original text,
  justica_gratuita text,
  emenda_inicial text,
  link_processo text,
  movimentacoes text,
  observacoes text,
  tratativas text,
  incompleto boolean,
  created_at timestamptz,
  updated_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if auth.role() <> 'service_role' and not public.usuario_pode_visualizar_status_processual() then
    raise exception 'Usuario sem acesso a carteira processual.';
  end if;
  return query
  select p.id, p.cliente_id, c.nome, p.numero_processo, p.reu,
    p.data_distribuicao, p.tribunal, p.comarca, p.vara,
    p.status_categoria, p.status_original, p.justica_gratuita,
    p.emenda_inicial, p.link_processo, p.movimentacoes,
    p.observacoes, p.tratativas, p.incompleto, p.created_at, p.updated_at
  from public.processos_clientes p
  join public.clientes c on c.id = p.cliente_id
  order by p.data_distribuicao desc nulls last, p.id desc;
end;
$$;

create or replace function public.listar_importacao_processos_protocolados(p_fonte text)
returns table (
  id bigint,
  cliente_id bigint,
  nome_cliente text,
  numero_processo text,
  data_distribuicao date,
  status_categoria text,
  status_original text,
  justica_gratuita text,
  emenda_inicial text,
  incompleto boolean,
  fontes_linhas integer[]
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if auth.role() <> 'service_role' and not public.usuario_pode_editar_status_processual() then
    raise exception 'Usuario sem acesso ao relatorio da importacao.';
  end if;
  return query
  select distinct p.id, p.cliente_id, c.nome, p.numero_processo,
    p.data_distribuicao, p.status_categoria, p.status_original,
    p.justica_gratuita, p.emenda_inicial, p.incompleto, p.fontes_linhas
  from public.importacoes_processos_protocolados_linhas i
  join public.processos_clientes p on p.id = i.processo_id
  join public.clientes c on c.id = p.cliente_id
  where i.fonte = p_fonte and i.erro is null
  order by p.id;
end;
$$;

