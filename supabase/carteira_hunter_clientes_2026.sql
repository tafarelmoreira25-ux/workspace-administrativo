-- Carteira Hunter da Equipe Jurídico.
-- Giullian organiza e delega perfis; o consultor registra o resultado.
-- Execute depois de configurar_sistema.sql e motor_operacional_tarefas_2026.sql.

begin;

alter table public.notificacoes_operacionais
  add column if not exists referencia_tipo text,
  add column if not exists referencia_id bigint;

create table if not exists public.prospeccoes_hunter (
  id bigint generated by default as identity primary key,
  hunter_id bigint not null references public.funcionarios(id) on delete restrict,
  consultor_id bigint references public.funcionarios(id) on delete restrict,
  nome_cliente text not null,
  whatsapp text not null,
  documento_sugerido text not null,
  cliente_com_processo boolean not null default false,
  numero_processo text,
  situacao_processo text,
  analise_breve text not null,
  status text not null default 'em_organizacao'
    check (status in ('em_organizacao', 'delegada', 'em_tratativa', 'concluida')),
  resultado text check (resultado is null or resultado in ('realizou_pagamento', 'nao_realizou_pagamento')),
  motivo_nao_pagamento text,
  observacao_consultor text,
  criada_por_email text not null default lower(coalesce(auth.jwt() ->> 'email', '')),
  delegada_em timestamptz,
  tratativa_iniciada_em timestamptz,
  concluida_em timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint prospeccao_processo_dados_check check (
    cliente_com_processo is false or
    (nullif(trim(numero_processo), '') is not null and nullif(trim(situacao_processo), '') is not null)
  ),
  constraint prospeccao_resultado_motivo_check check (
    resultado is distinct from 'nao_realizou_pagamento' or
    char_length(trim(coalesce(motivo_nao_pagamento, ''))) >= 5
  )
);

create table if not exists public.prospeccoes_hunter_historico (
  id bigint generated by default as identity primary key,
  prospeccao_id bigint not null references public.prospeccoes_hunter(id) on delete cascade,
  evento text not null,
  status_anterior text,
  status_novo text not null,
  dados jsonb not null default '{}'::jsonb,
  autor_email text not null default lower(coalesce(auth.jwt() ->> 'email', '')),
  created_at timestamptz not null default now()
);

create index if not exists prospeccoes_hunter_hunter_idx
  on public.prospeccoes_hunter(hunter_id, status, created_at desc);
create index if not exists prospeccoes_hunter_consultor_idx
  on public.prospeccoes_hunter(consultor_id, status, created_at desc);
create index if not exists prospeccoes_hunter_historico_idx
  on public.prospeccoes_hunter_historico(prospeccao_id, created_at desc);

create or replace function public.listar_prospeccoes_hunter()
returns table (
  id bigint,
  hunter_id bigint,
  hunter_nome text,
  consultor_id bigint,
  consultor_nome text,
  nome_cliente text,
  whatsapp text,
  documento_sugerido text,
  cliente_com_processo boolean,
  numero_processo text,
  situacao_processo text,
  analise_breve text,
  status text,
  resultado text,
  motivo_nao_pagamento text,
  observacao_consultor text,
  delegada_em timestamptz,
  tratativa_iniciada_em timestamptz,
  concluida_em timestamptz,
  created_at timestamptz,
  updated_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    p.id,
    p.hunter_id,
    h.nome as hunter_nome,
    p.consultor_id,
    c.nome as consultor_nome,
    p.nome_cliente,
    p.whatsapp,
    p.documento_sugerido,
    p.cliente_com_processo,
    p.numero_processo,
    p.situacao_processo,
    p.analise_breve,
    p.status,
    p.resultado,
    p.motivo_nao_pagamento,
    p.observacao_consultor,
    p.delegada_em,
    p.tratativa_iniciada_em,
    p.concluida_em,
    p.created_at,
    p.updated_at
  from public.prospeccoes_hunter p
  join public.funcionarios h on h.id = p.hunter_id
  left join public.funcionarios c on c.id = p.consultor_id
  where public.usuario_e_admin()
     or p.hunter_id = public.funcionario_id_autenticado()
     or p.consultor_id = public.funcionario_id_autenticado()
  order by
    case p.status
      when 'em_tratativa' then 1
      when 'delegada' then 2
      when 'em_organizacao' then 3
      else 4
    end,
    p.updated_at desc;
$$;

create or replace function public.salvar_prospeccao_hunter(
  p_prospeccao_id bigint,
  p_nome_cliente text,
  p_whatsapp text,
  p_documento_sugerido text,
  p_cliente_com_processo boolean,
  p_numero_processo text,
  p_situacao_processo text,
  p_analise_breve text,
  p_consultor_id bigint,
  p_delegar boolean default false
)
returns public.prospeccoes_hunter
language plpgsql
security definer
set search_path = public
as $$
declare
  v_hunter_id bigint;
  v_consultor_nome text;
  v_consultor_email text;
  v_anterior text;
  v_registro public.prospeccoes_hunter;
begin
  if lower(coalesce(auth.jwt() ->> 'email', '')) <> 'giullian@platino.com' then
    raise exception 'Somente Giullian pode cadastrar e delegar perfis da carteira Hunter.';
  end if;

  v_hunter_id := public.funcionario_id_autenticado();
  if v_hunter_id is null then
    raise exception 'O perfil interno da Giullian não foi encontrado.';
  end if;

  if nullif(trim(p_nome_cliente), '') is null
     or nullif(trim(p_whatsapp), '') is null
     or nullif(trim(p_documento_sugerido), '') is null
     or nullif(trim(p_analise_breve), '') is null then
    raise exception 'Nome, WhatsApp, documento sugerido e análise breve são obrigatórios.';
  end if;

  if coalesce(p_cliente_com_processo, false) and (
    nullif(trim(coalesce(p_numero_processo, '')), '') is null or
    nullif(trim(coalesce(p_situacao_processo, '')), '') is null
  ) then
    raise exception 'Número e situação do processo são obrigatórios.';
  end if;

  if p_delegar then
    select f.nome, f.email
      into v_consultor_nome, v_consultor_email
    from public.funcionarios f
    where f.id = p_consultor_id
      and f.ativo is not false
      and lower(coalesce(f.setor, '')) in ('jurídico', 'juridico')
      and lower(coalesce(f.cargo, '')) like '%consultor%';

    if v_consultor_email is null then
      raise exception 'Selecione um consultor jurídico ativo.';
    end if;
  end if;

  if p_prospeccao_id is null then
    insert into public.prospeccoes_hunter (
      hunter_id, consultor_id, nome_cliente, whatsapp, documento_sugerido,
      cliente_com_processo, numero_processo, situacao_processo, analise_breve,
      status, delegada_em
    ) values (
      v_hunter_id,
      p_consultor_id,
      trim(p_nome_cliente), trim(p_whatsapp), trim(p_documento_sugerido),
      coalesce(p_cliente_com_processo, false),
      case when p_cliente_com_processo then nullif(trim(p_numero_processo), '') end,
      case when p_cliente_com_processo then nullif(trim(p_situacao_processo), '') end,
      trim(p_analise_breve),
      case when p_delegar then 'delegada' else 'em_organizacao' end,
      case when p_delegar then now() end
    ) returning * into v_registro;
    v_anterior := null;
  else
    select p.status into v_anterior
    from public.prospeccoes_hunter p
    where p.id = p_prospeccao_id and p.hunter_id = v_hunter_id
    for update;

    if v_anterior is null then raise exception 'Perfil Hunter não encontrado.'; end if;
    if v_anterior <> 'em_organizacao' then
      raise exception 'Somente perfis em organização podem ser editados ou delegados.';
    end if;

    update public.prospeccoes_hunter
    set consultor_id = p_consultor_id,
        nome_cliente = trim(p_nome_cliente),
        whatsapp = trim(p_whatsapp),
        documento_sugerido = trim(p_documento_sugerido),
        cliente_com_processo = coalesce(p_cliente_com_processo, false),
        numero_processo = case when p_cliente_com_processo then nullif(trim(p_numero_processo), '') end,
        situacao_processo = case when p_cliente_com_processo then nullif(trim(p_situacao_processo), '') end,
        analise_breve = trim(p_analise_breve),
        status = case when p_delegar then 'delegada' else 'em_organizacao' end,
        delegada_em = case when p_delegar then now() else delegada_em end,
        updated_at = now()
    where id = p_prospeccao_id
    returning * into v_registro;
  end if;

  insert into public.prospeccoes_hunter_historico (
    prospeccao_id, evento, status_anterior, status_novo, dados
  ) values (
    v_registro.id,
    case when p_delegar then 'perfil_delegado' else 'perfil_salvo' end,
    v_anterior,
    v_registro.status,
    jsonb_build_object('consultor_id', v_registro.consultor_id)
  );

  if p_delegar then
    insert into public.notificacoes_operacionais (
      tarefa_id, funcionaria_id, destinatario_email, tipo, titulo, mensagem,
      referencia_tipo, referencia_id
    ) values (
      null, p_consultor_id, v_consultor_email, 'perfil_hunter_delegado',
      'Novo cliente indicado pela Hunter',
      trim(p_nome_cliente) || ' · ' || trim(p_documento_sugerido),
      'prospeccao_hunter', v_registro.id
    );
  end if;

  return v_registro;
end;
$$;

create or replace function public.movimentar_prospeccao_hunter(
  p_prospeccao_id bigint,
  p_acao text,
  p_resultado text default null,
  p_motivo text default null,
  p_observacao text default null
)
returns public.prospeccoes_hunter
language plpgsql
security definer
set search_path = public
as $$
declare
  v_consultor_id bigint;
  v_anterior text;
  v_hunter_email text;
  v_registro public.prospeccoes_hunter;
begin
  v_consultor_id := public.funcionario_id_autenticado();
  select p.* into v_registro
  from public.prospeccoes_hunter p
  where p.id = p_prospeccao_id
  for update;

  if v_registro.id is null then raise exception 'Perfil Hunter não encontrado.'; end if;
  if v_consultor_id is null or v_registro.consultor_id <> v_consultor_id then
    raise exception 'Somente o consultor responsável pode atualizar esta tratativa.';
  end if;

  v_anterior := v_registro.status;
  if p_acao = 'iniciar' then
    if v_anterior <> 'delegada' then raise exception 'A tratativa não está aguardando início.'; end if;
    update public.prospeccoes_hunter
    set status = 'em_tratativa', tratativa_iniciada_em = now(), updated_at = now()
    where id = p_prospeccao_id returning * into v_registro;
  elsif p_acao = 'concluir' then
    if v_anterior <> 'em_tratativa' then raise exception 'Inicie a tratativa antes de concluí-la.'; end if;
    if p_resultado not in ('realizou_pagamento', 'nao_realizou_pagamento') then
      raise exception 'Selecione se o cliente realizou ou não realizou o pagamento.';
    end if;
    if p_resultado = 'nao_realizou_pagamento'
       and char_length(trim(coalesce(p_motivo, ''))) < 5 then
      raise exception 'Informe o motivo de o cliente não ter realizado o pagamento.';
    end if;

    update public.prospeccoes_hunter
    set status = 'concluida',
        resultado = p_resultado,
        motivo_nao_pagamento = case when p_resultado = 'nao_realizou_pagamento' then trim(p_motivo) end,
        observacao_consultor = nullif(trim(coalesce(p_observacao, '')), ''),
        concluida_em = now(),
        updated_at = now()
    where id = p_prospeccao_id returning * into v_registro;
  else
    raise exception 'Ação Hunter inválida.';
  end if;

  insert into public.prospeccoes_hunter_historico (
    prospeccao_id, evento, status_anterior, status_novo, dados
  ) values (
    v_registro.id,
    case when p_acao = 'iniciar' then 'tratativa_iniciada' else 'tratativa_concluida' end,
    v_anterior,
    v_registro.status,
    jsonb_build_object('resultado', v_registro.resultado, 'motivo', v_registro.motivo_nao_pagamento)
  );

  if p_acao = 'concluir' then
    select lower(trim(f.email)) into v_hunter_email
    from public.funcionarios f where f.id = v_registro.hunter_id;

    insert into public.notificacoes_operacionais (
      tarefa_id, funcionaria_id, destinatario_email, tipo, titulo, mensagem,
      referencia_tipo, referencia_id
    ) values (
      null, v_registro.hunter_id, v_hunter_email, 'perfil_hunter_concluido',
      'Consultor devolveu o resultado',
      v_registro.nome_cliente || ' · ' ||
        case v_registro.resultado
          when 'realizou_pagamento' then 'Realizou pagamento'
          else 'Não realizou pagamento'
        end,
      'prospeccao_hunter', v_registro.id
    );
  end if;

  return v_registro;
end;
$$;

