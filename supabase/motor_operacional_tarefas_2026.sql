create or replace function public.delegar_tarefa_operacional(
  p_cliente_id bigint,p_tratativa_id bigint,p_nome_cliente text,p_tipo_codigo text,
  p_titulo text,p_solicitacao text,p_resultado_esperado text,p_setor_solicitante text,
  p_setor_executor text,p_funcionaria_id bigint,p_prazo_limite timestamptz,
  p_prioridade text default 'normal',p_criterios jsonb default null
) returns public.tarefas language plpgsql security definer set search_path=public as $$
declare t public.tarefas; sla public.tipos_tarefa_sla; email_resp text; cliente_final_id bigint; codigo_cliente text;
begin
  if not public.usuario_e_admin() then raise exception 'Somente a supervisao pode delegar tarefas.'; end if;
  if nullif(trim(p_nome_cliente),'') is null then raise exception 'Cliente obrigatorio.'; end if;
  if p_funcionaria_id is null then raise exception 'Responsavel obrigatorio.'; end if;
  if p_prazo_limite is null or p_prazo_limite <= now() then raise exception 'Prazo futuro obrigatorio.'; end if;
  if nullif(trim(p_titulo),'') is null or nullif(trim(p_solicitacao),'') is null or nullif(trim(p_resultado_esperado),'') is null then
    raise exception 'Solicitacao e resultado esperado sao obrigatorios.';
  end if;
  select * into sla from public.tipos_tarefa_sla where codigo=p_tipo_codigo and ativo;
  if sla.codigo is null then raise exception 'Tipo de tarefa invalido.'; end if;
  select email into email_resp from public.funcionarios where id=p_funcionaria_id and ativo is not false;
  if email_resp is null then raise exception 'Responsavel ativo nao encontrado.'; end if;
  cliente_final_id:=p_cliente_id;
  if cliente_final_id is null then
    select id into cliente_final_id from public.clientes where lower(trim(nome))=lower(trim(p_nome_cliente)) and ativo order by id desc limit 1;
  end if;
  if cliente_final_id is null then
    perform pg_advisory_xact_lock(hashtext('cliente-operacional'));
    codigo_cliente:='CLI-'||to_char(current_date,'YYYYMMDD')||'-'||lpad((select (count(*)+1)::text from public.clientes where created_at::date=current_date),3,'0');
    insert into public.clientes(codigo_interno,nome) values(codigo_cliente,trim(p_nome_cliente)) returning id into cliente_final_id;
  end if;
  insert into public.tarefas(titulo,descricao,funcionaria_id,pontos_tarefa,data_limite,prazo_limite,status,prioridade,
    categoria,cliente_id,tratativa_id,nome_cliente,tipo_tarefa_codigo,acao_operacional,setor_solicitante,
    setor_executor,resultado_esperado,criterios_conclusao,solicitante_email,origem,recebida_em)
  values(trim(p_titulo),trim(p_solicitacao),p_funcionaria_id,0,p_prazo_limite::date,p_prazo_limite,'delegada',p_prioridade,
    sla.nome,cliente_final_id,p_tratativa_id,trim(p_nome_cliente),sla.codigo,sla.nome,trim(p_setor_solicitante),
    trim(p_setor_executor),trim(p_resultado_esperado),coalesce(p_criterios,sla.checklist_padrao),
    lower(coalesce(auth.jwt()->>'email','')), 'operacional',now()) returning * into t;
  perform public.registrar_evento_tarefa(t.id,'criada',null,'delegada','Tarefa criada e delegada.',jsonb_build_object('responsavel_id',p_funcionaria_id,'setor_executor',p_setor_executor));
  perform public.notificar_tarefa(t.id,p_funcionaria_id,email_resp,'nova_tarefa','Nova tarefa recebida',coalesce(t.id_externo,t.id::text)||' · '||t.titulo);
  return t;
end $$;

create or replace function public.movimentar_tarefa_operacional(
  p_tarefa_id bigint,p_acao text,p_motivo text default null,p_checklist jsonb default null,
  p_observacoes text default null,p_nome_arquivo text default null,p_drive_url text default null,
  p_crm_atualizado boolean default false,p_planilha_atualizada boolean default false
) returns public.tarefas language plpgsql security definer set search_path=public as $$
declare t public.tarefas; anterior text; uid bigint:=public.funcionario_id_autenticado(); email_autor text:=lower(coalesce(auth.jwt()->>'email',''));
  checklist_ok boolean; destino text; descricao_evento text;
begin
  select * into t from public.tarefas where id=p_tarefa_id for update;
  if t.id is null then raise exception 'Tarefa nao encontrada.'; end if;
  anterior:=t.status;
  if p_acao in ('aceitar','iniciar','aguardar','devolver_conferencia','devolver_solicitante')
     and not public.usuario_e_admin() and t.funcionaria_id is distinct from uid then raise exception 'Tarefa nao atribuida ao usuario.'; end if;
  if p_acao in ('aprovar','corrigir','cancelar') and not public.usuario_e_admin() then raise exception 'Acao restrita a supervisao.'; end if;

  if p_acao='aceitar' and t.status='delegada' then destino:='recebida'; descricao_evento:='Tarefa aceita pelo responsavel.'; t.aceita_em:=now();
  elsif p_acao='iniciar' and t.status in ('recebida','devolvida_correcao','aguardando_informacao') then destino:='em_execucao'; descricao_evento:='Execucao iniciada.'; t.execucao_iniciada_em:=coalesce(t.execucao_iniciada_em,now());
  elsif p_acao='aguardar' and t.status in ('recebida','em_execucao') then
    if char_length(trim(coalesce(p_motivo,'')))<10 then raise exception 'Informe o motivo da espera.'; end if;
    destino:='aguardando_informacao';descricao_evento:='Tarefa aguardando informacao: '||trim(p_motivo);t.bloqueio_motivo:=trim(p_motivo);
  elsif p_acao='devolver_solicitante' and t.status in ('delegada','recebida','em_execucao','aguardando_informacao') then
    if char_length(trim(coalesce(p_motivo,'')))<10 then raise exception 'Justificativa obrigatoria.'; end if;
    destino:='devolvida';descricao_evento:='Tarefa devolvida ao solicitante: '||trim(p_motivo);
  elsif p_acao='devolver_conferencia' and t.status='em_execucao' then
    checklist_ok := not exists(
      select 1 from jsonb_array_elements_text(t.criterios_conclusao) as criterio(valor)
      where coalesce((p_checklist->>criterio.valor)::boolean,false)=false
    );
    if not checklist_ok then raise exception 'Conclua todos os criterios da tarefa.'; end if;
    if nullif(trim(coalesce(p_observacoes,'')),'') is null then raise exception 'Devolutiva obrigatoria.'; end if;
    if trim(coalesce(p_nome_arquivo,'')) !~* '^\d{4}-\d{2}-\d{2}(_[A-Z0-9]+(-[A-Z0-9]+)*){4}\.[A-Z0-9]{2,5}$' then
      raise exception 'Nomenclatura invalida. Use DATA_CLIENTE_TIPO_STATUS_RESPONSAVEL.extensao.';
    end if;
    if trim(coalesce(p_drive_url,'')) !~* '^https://(drive|docs)\.google\.com/' then raise exception 'Link do Drive obrigatorio.'; end if;
    if not coalesce(p_crm_atualizado,false) or not coalesce(p_planilha_atualizada,false) then raise exception 'CRM e Planilha Geral devem estar atualizados.'; end if;
    destino:='devolvida_conferencia';descricao_evento:='Execucao devolvida para conferencia.';t.devolvida_conferencia_em:=now();
    t.checklist_execucao:=coalesce(p_checklist,'{}');t.observacoes_devolutiva:=trim(p_observacoes);t.nome_arquivo_evidencia:=trim(p_nome_arquivo);
    t.evidencia_url:=trim(p_drive_url);t.crm_atualizado:=true;t.planilha_atualizada:=true;t.drive_arquivado:=true;
  elsif p_acao='aprovar' and t.status='devolvida_conferencia' then destino:='concluida';descricao_evento:='Tarefa conferida e aprovada.';t.conferida_em:=now();t.conferida_por_email:=email_autor;t.concluida_em:=now();
  elsif p_acao='corrigir' and t.status='devolvida_conferencia' then
    if char_length(trim(coalesce(p_motivo,'')))<10 then raise exception 'Descreva a correcao necessaria.'; end if;
    destino:='devolvida_correcao';descricao_evento:='Correcao solicitada: '||trim(p_motivo);
  elsif p_acao='cancelar' and t.status<>'concluida' then destino:='cancelada';descricao_evento:='Tarefa cancelada: '||trim(coalesce(p_motivo,'Sem continuidade'));
  else raise exception 'Transicao % invalida para o status %.',p_acao,t.status; end if;

  perform set_config('platino.motor_operacional','1',true);
  update public.tarefas set status=destino,aceita_em=t.aceita_em,execucao_iniciada_em=t.execucao_iniciada_em,
    bloqueio_motivo=t.bloqueio_motivo,devolvida_conferencia_em=t.devolvida_conferencia_em,
    checklist_execucao=t.checklist_execucao,observacoes_devolutiva=t.observacoes_devolutiva,
    nome_arquivo_evidencia=t.nome_arquivo_evidencia,evidencia_url=t.evidencia_url,crm_atualizado=t.crm_atualizado,
    planilha_atualizada=t.planilha_atualizada,drive_arquivado=t.drive_arquivado,conferida_em=t.conferida_em,
    conferida_por_email=t.conferida_por_email,concluida_em=t.concluida_em,updated_at=now(),versao=versao+1
  where id=t.id returning * into t;
  perform public.registrar_evento_tarefa(t.id,p_acao,anterior,destino,descricao_evento,jsonb_build_object('motivo',p_motivo));
  if destino in ('devolvida','devolvida_conferencia') then perform public.notificar_tarefa(t.id,null,t.solicitante_email,destino,'Tarefa requer conferencia',descricao_evento); end if;
  if destino='devolvida_correcao' then perform public.notificar_tarefa(t.id,t.funcionaria_id,null,'correcao','Correcao solicitada',descricao_evento); end if;
  return t;
end $$;

create or replace view public.tarefas_operacionais_resumo with(security_invoker=true) as
select t.*,
  case when t.status not in ('concluida','cancelada','arquivada') and coalesce(t.prazo_limite,t.data_limite::timestamptz)<now() then 'atrasada'
       when t.status not in ('concluida','cancelada','arquivada') and coalesce(t.prazo_limite,t.data_limite::timestamptz)<=now()+interval '30 minutes' then 'vence_em_30_minutos'
       else 'normal' end situacao_sla,
  case when t.execucao_iniciada_em is not null then extract(epoch from (coalesce(t.concluida_em,now())-t.execucao_iniciada_em))/60 end tempo_execucao_minutos,
  case when t.prazo_limite is not null and t.concluida_em>t.prazo_limite then extract(epoch from (t.concluida_em-t.prazo_limite))/60 else 0 end tempo_excedido_minutos
from public.tarefas t;

