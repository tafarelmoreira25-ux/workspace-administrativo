create or replace function public.proteger_edicao_tarefa_funcionaria()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if coalesce(current_setting('platino.motor_operacional',true),'0')='1' then return new; end if;
  if old.origem='operacional' and new.status is distinct from old.status then
    raise exception 'Use a transicao operacional correspondente; alteracao direta de status bloqueada.';
  end if;
  if public.usuario_e_admin() then return new; end if;
  if new.funcionaria_id is distinct from old.funcionaria_id
     or new.exibir_tv is distinct from old.exibir_tv
     or new.cliente_id is distinct from old.cliente_id
     or new.tratativa_id is distinct from old.tratativa_id
     or new.status is distinct from old.status then
    raise exception 'Use as acoes da tarefa; alteracao direta nao autorizada.';
  end if;
  return new;
end $$;

drop trigger if exists proteger_edicao_tarefa_funcionaria on public.tarefas;
create trigger proteger_edicao_tarefa_funcionaria before update on public.tarefas
for each row execute function public.proteger_edicao_tarefa_funcionaria();

