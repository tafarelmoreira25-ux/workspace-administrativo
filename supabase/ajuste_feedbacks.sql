-- AJUSTE DE ENTREGA E LEITURA DOS FEEDBACKS
-- Execute todo este arquivo no SQL Editor do Supabase.

begin;

create table if not exists public.feedbacks (
  id bigint generated by default as identity primary key,
  funcionaria_id bigint not null references public.funcionarios(id),
  mensagem text not null,
  tipo text not null default 'positivo',
  created_at timestamptz not null default now()
);

create index if not exists feedbacks_funcionaria_created_at_idx
on public.feedbacks (funcionaria_id, created_at desc);

create or replace function public.usuario_e_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select lower(trim(coalesce(auth.jwt() ->> 'email', '')))
    = 'tafarel@platino.com';
$$;

create or replace function public.feedback_pertence_ao_usuario(
  p_funcionaria_id bigint
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.funcionarios funcionario
    where funcionario.id = p_funcionaria_id
      and lower(trim(funcionario.email)) =
        lower(trim(coalesce(auth.jwt() ->> 'email', '')))
  );
$$;

revoke all on function public.usuario_e_admin() from public;
revoke all on function public.feedback_pertence_ao_usuario(bigint) from public;
grant execute on function public.usuario_e_admin() to authenticated;
grant execute on function public.feedback_pertence_ao_usuario(bigint)
  to authenticated;

alter table public.feedbacks enable row level security;

revoke all on public.feedbacks from anon;
grant select, insert on public.feedbacks to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists "Equipe consulta feedbacks permitidos"
on public.feedbacks;
drop policy if exists "Funcionaria consulta feedbacks recebidos"
on public.feedbacks;
create policy "Funcionaria consulta feedbacks recebidos"
on public.feedbacks for select to authenticated
using (
  public.usuario_e_admin()
  or public.feedback_pertence_ao_usuario(funcionaria_id)
);

drop policy if exists "Supervisor registra feedbacks"
on public.feedbacks;
create policy "Supervisor registra feedbacks"
on public.feedbacks for insert to authenticated
with check (
  public.usuario_e_admin()
  and exists (
    select 1
    from public.funcionarios funcionario
    where funcionario.id = funcionaria_id
  )
);

do $$
begin
  if exists (
    select 1
    from pg_publication
    where pubname = 'supabase_realtime'
  ) and not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'feedbacks'
  ) then
    alter publication supabase_realtime add table public.feedbacks;
  end if;
end;
$$;

notify pgrst, 'reload schema';

commit;

