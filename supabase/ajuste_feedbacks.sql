select
  feedback.id,
  feedback.created_at,
  feedback.tipo,
  funcionario.id as funcionaria_id,
  funcionario.nome,
  lower(trim(funcionario.email)) as email_destinatario,
  feedback.mensagem
from public.feedbacks feedback
join public.funcionarios funcionario
  on funcionario.id = feedback.funcionaria_id
order by feedback.created_at desc;
