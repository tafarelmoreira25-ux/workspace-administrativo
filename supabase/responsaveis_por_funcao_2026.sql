-- CONFIGURAÇÃO CENTRALIZADA DE RESPONSÁVEIS POR FUNÇÃO
-- Tabela para armazenar o mapeamento de categorias de tarefas para responsáveis
-- Execute este arquivo no SQL Editor do Supabase

create table if not exists public.responsaveis_por_funcao (
  id bigint generated by default as identity primary key,
  categoria_tarefa text not null unique,
  funcionaria_id bigint references public.funcionarios(id) on delete set null,
  configurado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

-- Política de segurança RLS: todos autenticados podem ler, só o admin pode escrever
alter table public.responsaveis_por_funcao enable row level security;

drop policy if exists "Usuários podem ler responsáveis por função" on public.responsaveis_por_funcao;
drop policy if exists "Só admin pode criar responsáveis por função" on public.responsaveis_por_funcao;
drop policy if exists "Só admin pode editar responsáveis por função" on public.responsaveis_por_funcao;

create policy "Usuários podem ler responsáveis por função"
  on public.responsaveis_por_funcao
  for select
  using (auth.role() = 'authenticated');

create policy "Só admin pode criar responsáveis por função"
  on public.responsaveis_por_funcao
  for insert
  with check (auth.jwt() ->> 'email' = 'tafa@administrativo.com');

create policy "Só admin pode editar responsáveis por função"
  on public.responsaveis_por_funcao
  for update
  using (auth.jwt() ->> 'email' = 'tafa@administrativo.com')
  with check (auth.jwt() ->> 'email' = 'tafa@administrativo.com');

-- RPC para carregar todos os responsáveis mapeados
create or replace function public.carregar_responsaveis_por_funcao()
returns table (categoria_tarefa text, funcionaria_id bigint, nome_funcionario text)
language sql
stable
as $$
select 
  rpf.categoria_tarefa,
  rpf.funcionaria_id,
  coalesce(f.nome, 'Sem responsável') as nome_funcionario
from public.responsaveis_por_funcao rpf
left join public.funcionarios f on rpf.funcionaria_id = f.id;
$$;

-- RPC para atualizar um responsável por função
create or replace function public.atualizar_responsavel_funcao(
  p_categoria_tarefa text,
  p_funcionaria_id bigint
)
returns boolean
language plpgsql
security definer
as $$
declare
  v_admin_email text := 'tafa@administrativo.com';
begin
  -- Verificação de permissão
  if (select (auth.jwt() ->> 'email') = v_admin_email) is false then
    return false;
  end if;

  -- Inserir ou atualizar
  insert into public.responsaveis_por_funcao (categoria_tarefa, funcionaria_id)
  values (p_categoria_tarefa, p_funcionaria_id)
  on conflict (categoria_tarefa)
  do update
  set funcionaria_id = excluded.funcionaria_id,
      atualizado_em = now();

  return true;
end;
$$;

-- RPC para salvar múltiplos responsáveis de uma vez (bulk update)
create or replace function public.salvar_todos_responsaveis_funcao(
  p_mapeamento jsonb
)
returns boolean
language plpgsql
security definer
as $$
declare
  v_admin_email text := 'tafa@administrativo.com';
  v_categoria text;
  v_funcionaria_id bigint;
begin
  -- Verificação de permissão
  if (select (auth.jwt() ->> 'email') = v_admin_email) is false then
    return false;
  end if;

  -- Iterar sobre o objeto JSON e atualizar cada categoria
  for v_categoria, v_funcionaria_id in
    select key, value::bigint from jsonb_each(p_mapeamento)
  loop
    insert into public.responsaveis_por_funcao (categoria_tarefa, funcionaria_id)
    values (v_categoria, nullif(v_funcionaria_id, 0))
    on conflict (categoria_tarefa)
    do update
    set funcionaria_id = excluded.funcionaria_id,
        atualizado_em = now();
  end loop;

  return true;
end;
$$;
