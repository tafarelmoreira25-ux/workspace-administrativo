-- Execute depois de motor_operacional_tarefas_2026.sql e evolucao_gestao_base.sql.

begin;

-- O tipo operacional (tipos_tarefa_sla.codigo) passa a ser a fonte de verdade.
-- A lista antiga de categorias no tarefas_categoria_check bloqueava novas ações.
alter table public.tarefas
  drop constraint if exists tarefas_categoria_check;

alter table public.funcionarios
  add column if not exists perfil text not null default 'colaborador';

update public.funcionarios
set perfil = 'supervisor'
where lower(trim(email)) = 'tafarel@platino.com'
   or lower(coalesce(cargo, '')) like '%supervisor%';

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.funcionarios'::regclass
      and conname = 'funcionarios_perfil_check'
  ) then
    alter table public.funcionarios
      add constraint funcionarios_perfil_check
      check (perfil in ('supervisor', 'colaborador'));
  end if;
end;
$$;

-- A autorização deixa de depender do nome da pessoa no React.
create or replace function public.usuario_e_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    lower(trim(coalesce(auth.jwt() ->> 'email', ''))) = 'tafarel@platino.com'
    or exists (
      select 1
      from public.funcionarios f
      where lower(trim(f.email)) = lower(trim(coalesce(auth.jwt() ->> 'email', '')))
        and f.ativo is not false
        and f.perfil = 'supervisor'
    );
$$;

revoke all on function public.usuario_e_admin() from public;
grant execute on function public.usuario_e_admin() to authenticated;

create table if not exists public.responsaveis_por_funcao (
  id bigint generated by default as identity primary key,
  categoria_tarefa text not null unique,
  funcionaria_id bigint references public.funcionarios(id) on delete set null,
  configurado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

alter table public.responsaveis_por_funcao enable row level security;
revoke all on public.responsaveis_por_funcao from anon;
grant select on public.responsaveis_por_funcao to authenticated;

drop policy if exists "Todos podem ler responsáveis por função"
  on public.responsaveis_por_funcao;
drop policy if exists "Só admin pode criar responsáveis por função"
  on public.responsaveis_por_funcao;
drop policy if exists "Só admin pode editar responsáveis por função"
  on public.responsaveis_por_funcao;
drop policy if exists "Supervisor gerencia responsáveis por função"
  on public.responsaveis_por_funcao;

create policy "Todos podem ler responsáveis por função"
on public.responsaveis_por_funcao
for select to authenticated
using (true);

create policy "Supervisor gerencia responsáveis por função"
on public.responsaveis_por_funcao
for all to authenticated
using (public.usuario_e_admin())
with check (public.usuario_e_admin());

-- DROP é obrigatório se uma instalação antiga tiver outro retorno para a RPC.
drop function if exists public.carregar_responsaveis_por_funcao();
drop function if exists public.obter_responsavel_por_categoria(text);
drop function if exists public.atualizar_responsavel_funcao(text, bigint);
drop function if exists public.salvar_todos_responsaveis_funcao(jsonb);

create function public.carregar_responsaveis_por_funcao()
returns table (
  categoria_tarefa text,
  funcionaria_id bigint,
  nome_funcionario text
)
language sql
stable
security definer
set search_path = public
as $$
  select
    r.categoria_tarefa,
    r.funcionaria_id,
    coalesce(f.nome, 'Sem responsável')
  from public.responsaveis_por_funcao r
  left join public.funcionarios f on f.id = r.funcionaria_id
  order by r.categoria_tarefa;
$$;

create function public.obter_responsavel_por_categoria(p_categoria text)
returns table (
  categoria_tarefa text,
  funcionaria_id bigint,
  nome_funcionario text
)
language sql
stable
security definer
set search_path = public
as $$
  select
    r.categoria_tarefa,
    r.funcionaria_id,
    coalesce(f.nome, 'Sem responsável')
  from public.responsaveis_por_funcao r
  left join public.funcionarios f on f.id = r.funcionaria_id
  where r.categoria_tarefa = trim(p_categoria);
$$;

create function public.atualizar_responsavel_funcao(
  p_categoria_tarefa text,
  p_funcionaria_id bigint
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.usuario_e_admin() then
    raise exception 'Somente supervisores podem alterar o roteamento de tarefas.';
  end if;

  if p_funcionaria_id is not null and not exists (
    select 1 from public.funcionarios
    where id = p_funcionaria_id and ativo is not false
  ) then
    raise exception 'O responsável selecionado não está ativo.';
  end if;

  insert into public.responsaveis_por_funcao (categoria_tarefa, funcionaria_id)
  values (trim(p_categoria_tarefa), p_funcionaria_id)
  on conflict (categoria_tarefa) do update
  set funcionaria_id = excluded.funcionaria_id,
      atualizado_em = now();

  return true;
end;
$$;

create function public.salvar_todos_responsaveis_funcao(p_mapeamento jsonb)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_categoria text;
  v_id_texto text;
  v_funcionaria_id bigint;
begin
  if not public.usuario_e_admin() then
    raise exception 'Somente supervisores podem alterar o roteamento de tarefas.';
  end if;

  for v_categoria, v_id_texto in
    select key, value from jsonb_each_text(coalesce(p_mapeamento, '{}'::jsonb))
  loop
    v_funcionaria_id := case
      when nullif(trim(v_id_texto), '') is null
        or lower(trim(v_id_texto)) = 'null'
        or trim(v_id_texto) = '0'
      then null
      else trim(v_id_texto)::bigint
    end;

    if v_funcionaria_id is not null and not exists (
      select 1 from public.funcionarios
      where id = v_funcionaria_id and ativo is not false
    ) then
      raise exception 'Responsável inativo ou inexistente na categoria %.', v_categoria;
    end if;

    insert into public.responsaveis_por_funcao (categoria_tarefa, funcionaria_id)
    values (trim(v_categoria), v_funcionaria_id)
    on conflict (categoria_tarefa) do update
    set funcionaria_id = excluded.funcionaria_id,
        atualizado_em = now();
  end loop;

  return true;
end;
$$;

grant execute on function public.carregar_responsaveis_por_funcao()
  to authenticated;
grant execute on function public.obter_responsavel_por_categoria(text)
  to authenticated;
grant execute on function public.atualizar_responsavel_funcao(text, bigint)
  to authenticated;
grant execute on function public.salvar_todos_responsaveis_funcao(jsonb)
  to authenticated;

-- Proteção final: equipe informada e equipe da pessoa precisam ser iguais.
create or replace function public.normalizar_equipe_operacional(p_setor text)
returns text
language sql
immutable
set search_path = public
as $$
  select case
    when lower(coalesce(p_setor, '')) like '%jur%'
      or lower(coalesce(p_setor, '')) like '%processual%'
      then 'juridico'
    when lower(coalesce(p_setor, '')) like '%administr%'
      or lower(trim(coalesce(p_setor, ''))) = 'adm'
      then 'administrativo'
    else null
  end;
$$;

create or replace function public.validar_equipe_responsavel_tarefa()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_setor_responsavel text;
  v_equipe_responsavel text;
  v_equipe_tarefa text;
begin
  if new.origem is distinct from 'operacional' then
    return new;
  end if;

  select setor into v_setor_responsavel
  from public.funcionarios
  where id = new.funcionaria_id and ativo is not false;

  v_equipe_responsavel := public.normalizar_equipe_operacional(v_setor_responsavel);
  v_equipe_tarefa := public.normalizar_equipe_operacional(new.setor_executor);

  if v_equipe_tarefa is null then
    raise exception 'A equipe executora deve ser Administrativo ou Jurídico.';
  end if;
  if v_equipe_responsavel is null then
    raise exception 'O responsável precisa ter uma equipe válida no cadastro.';
  end if;
  if v_equipe_tarefa <> v_equipe_responsavel then
    raise exception 'O responsável selecionado não pertence à equipe executora.';
  end if;

  return new;
end;
$$;

drop trigger if exists validar_equipe_responsavel_tarefa on public.tarefas;
create trigger validar_equipe_responsavel_tarefa
before insert or update of funcionaria_id, setor_executor on public.tarefas
for each row execute function public.validar_equipe_responsavel_tarefa();

notify pgrst, 'reload schema';

commit;
