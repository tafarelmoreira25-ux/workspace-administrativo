-- Impede que o update direto usado pelas tarefas comuns conclua uma etapa de esteira.
create or replace function public.proteger_edicao_tarefa_funcionaria()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if public.usuario_e_admin() then return new; end if;
  if new.funcionaria_id is distinct from old.funcionaria_id
     or new.exibir_tv is distinct from old.exibir_tv
     or new.cliente_id is distinct from old.cliente_id
     or new.instancia_esteira_id is distinct from old.instancia_esteira_id
     or new.etapa_modelo_id is distinct from old.etapa_modelo_id
     or new.codigo_etapa is distinct from old.codigo_etapa then
    raise exception 'A colaboradora nao pode alterar estrutura, cliente ou responsavel.';
  end if;
  if old.origem='esteira' and new.status='concluida'
     and coalesce(current_setting('celios.conclusao_esteira',true),'0') <> '1' then
    raise exception 'Etapas de esteira devem ser concluidas pelo fluxo transacional.';
  end if;
  if new.status is distinct from old.status and new.status <> 'concluida' then
    raise exception 'Alteracao de status nao autorizada.';
  end if;
  return new;
end $$;

drop trigger if exists proteger_edicao_tarefa_funcionaria on public.tarefas;
create trigger proteger_edicao_tarefa_funcionaria
before update on public.tarefas for each row
execute function public.proteger_edicao_tarefa_funcionaria();

-- Registra mudancas sem apagar ou substituir o historico operacional.
create or replace function public.auditar_tarefa_esteira()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if new.instancia_esteira_id is not null and (
    new.status is distinct from old.status
    or new.funcionaria_id is distinct from old.funcionaria_id
    or new.evidencia_url is distinct from old.evidencia_url
  ) then
    insert into public.esteiras_eventos(instancia_esteira_id,tarefa_id,tipo,descricao,dados)
    values(new.instancia_esteira_id,new.id,'tarefa_alterada','Alteracao registrada na etapa.',
      jsonb_build_object('status_anterior',old.status,'status_novo',new.status,
        'responsavel_anterior',old.funcionaria_id,'responsavel_novo',new.funcionaria_id));
  end if;
  return new;
end $$;

drop trigger if exists auditar_tarefa_esteira on public.tarefas;
create trigger auditar_tarefa_esteira after update on public.tarefas
for each row execute function public.auditar_tarefa_esteira();

-- Supervisor cria a instancia e todas as etapas bloqueadas; somente a primeira e liberada.
create or replace function public.iniciar_esteira_administrativa(
  p_cliente_id bigint, p_modelo_esteira_id bigint, p_funcionaria_id bigint
) returns public.instancias_esteira
language plpgsql security definer set search_path=public as $$
declare instancia public.instancias_esteira; primeira_ordem integer;
begin
  if not public.usuario_e_admin() then raise exception 'Acesso restrito ao supervisor.'; end if;
  if not exists(select 1 from public.clientes where id=p_cliente_id and ativo) then raise exception 'Cliente ativo nao encontrado.'; end if;
  if not exists(select 1 from public.funcionarios where id=p_funcionaria_id and ativo) then raise exception 'Responsavel ativa nao encontrada.'; end if;
  if not exists(select 1 from public.modelos_esteira where id=p_modelo_esteira_id and ativo) then raise exception 'Modelo ativo nao encontrado.'; end if;

  insert into public.instancias_esteira(cliente_id,modelo_esteira_id)
  values(p_cliente_id,p_modelo_esteira_id) returning * into instancia;
  select min(ordem) into primeira_ordem from public.modelos_etapas where modelo_esteira_id=p_modelo_esteira_id and ativo;

  insert into public.tarefas(titulo,descricao,funcionaria_id,pontos_tarefa,data_limite,status,
    prioridade,categoria,exibir_tv,tarefa_manual,updated_at,cliente_id,instancia_esteira_id,
    etapa_modelo_id,codigo_etapa,origem,liberada_em,bloqueada_em)
  select e.titulo,e.descricao,p_funcionaria_id,0,
    case when e.ordem=primeira_ordem then current_date+e.prazo_padrao_dias else null end,
    case when e.ordem=primeira_ordem then 'nova' else 'bloqueada' end,
    'normal',null,e.ordem=primeira_ordem,false,now(),p_cliente_id,instancia.id,e.id,e.codigo,'esteira',
    case when e.ordem=primeira_ordem then now() end,
    case when e.ordem<>primeira_ordem then now() end
  from public.modelos_etapas e where e.modelo_esteira_id=p_modelo_esteira_id and e.ativo
  order by e.ordem on conflict (instancia_esteira_id,codigo_etapa) where instancia_esteira_id is not null and codigo_etapa is not null do nothing;

  insert into public.alertas_esteira(instancia_esteira_id,tarefa_id,funcionaria_id,tipo,mensagem)
  select instancia.id,t.id,t.funcionaria_id,'liberada','Nova etapa administrativa liberada.'
  from public.tarefas t where t.instancia_esteira_id=instancia.id and t.status='nova';
  return instancia;
end $$;

create or replace function public.criar_subprocesso_esteira_interno(
  p_instancia_pai_id bigint, p_modelo_nome text, p_etapa_origem text, p_funcionaria_id bigint
) returns public.instancias_esteira
language plpgsql security definer set search_path=public as $$
declare pai public.instancias_esteira; modelo_id bigint; instancia public.instancias_esteira; primeira integer;
begin
  select * into pai from public.instancias_esteira where id=p_instancia_pai_id and status='ativa' for update;
  if pai.id is null then raise exception 'Esteira principal ativa nao encontrada.'; end if;
  select id into modelo_id from public.modelos_esteira
  where nome=p_modelo_nome and tipo_fluxo='subprocesso' and ativo order by versao desc limit 1;
  if modelo_id is null then raise exception 'Modelo de subprocesso nao encontrado.'; end if;
  if exists(select 1 from public.instancias_esteira where instancia_pai_id=pai.id and modelo_esteira_id=modelo_id and status='ativa') then
    select * into instancia from public.instancias_esteira where instancia_pai_id=pai.id and modelo_esteira_id=modelo_id and status='ativa' limit 1;
    return instancia;
  end if;
  insert into public.instancias_esteira(cliente_id,modelo_esteira_id,instancia_pai_id,etapa_origem_codigo)
  values(pai.cliente_id,modelo_id,pai.id,p_etapa_origem) returning * into instancia;
  select min(ordem) into primeira from public.modelos_etapas where modelo_esteira_id=modelo_id and ativo;
  insert into public.tarefas(titulo,descricao,funcionaria_id,pontos_tarefa,data_limite,status,prioridade,
    categoria,exibir_tv,tarefa_manual,updated_at,cliente_id,instancia_esteira_id,etapa_modelo_id,
    codigo_etapa,origem,liberada_em,bloqueada_em)
  select e.titulo,e.descricao,p_funcionaria_id,0,
    case when e.ordem=primeira then current_date+e.prazo_padrao_dias end,
    case when e.ordem=primeira then 'nova' else 'bloqueada' end,'normal',null,e.ordem=primeira,
    false,now(),pai.cliente_id,instancia.id,e.id,e.codigo,'esteira',
    case when e.ordem=primeira then now() end,case when e.ordem<>primeira then now() end
  from public.modelos_etapas e where e.modelo_esteira_id=modelo_id and e.ativo order by e.ordem
  on conflict(instancia_esteira_id,codigo_etapa) where instancia_esteira_id is not null and codigo_etapa is not null do nothing;
  return instancia;
end $$;

revoke all on function public.criar_subprocesso_esteira_interno(bigint,text,text,bigint) from public;

-- Conclusao, evidencia, decisao condicional e liberacao ocorrem na mesma transacao.
create or replace function public.concluir_tarefa_e_liberar_proxima(
  p_tarefa_id bigint, p_evidencia_url text default null, p_resultado text default null
) returns jsonb
language plpgsql security definer set search_path=public as $$
declare atual public.tarefas; etapa public.modelos_etapas; proxima public.tarefas;
  usuario_id bigint; proximo_codigo text; subinstancia public.instancias_esteira;
begin
  select * into atual from public.tarefas where id=p_tarefa_id for update;
  if atual.id is null or atual.origem<>'esteira' then raise exception 'Etapa de esteira nao encontrada.'; end if;
  usuario_id:=public.funcionario_id_autenticado();
  if not public.usuario_e_admin() and atual.funcionaria_id is distinct from usuario_id then raise exception 'Tarefa nao autorizada.'; end if;
  if atual.status not in ('nova','em_andamento','em_revisao') then raise exception 'A tarefa nao esta disponivel para conclusao.'; end if;
  select * into etapa from public.modelos_etapas where id=atual.etapa_modelo_id;
  if etapa.evidencia_obrigatoria and nullif(trim(coalesce(p_evidencia_url,'')),'') is null then raise exception 'Evidencia obrigatoria.'; end if;

  if atual.codigo_etapa='ADM-007' and p_resultado='pendencia' then
    update public.tarefas set status='aguardando_cliente',motivo_bloqueio='Documentacao pendente',updated_at=now() where id=atual.id;
    insert into public.alertas_esteira(instancia_esteira_id,tarefa_id,funcionaria_id,tipo,mensagem,destinada_supervisor)
    values(atual.instancia_esteira_id,atual.id,atual.funcionaria_id,'bloqueio','Etapa aguardando documentos do cliente.',true)
    on conflict do nothing;
    return jsonb_build_object('tarefa_concluida',null,'proxima_tarefa',null,'status','aguardando_cliente');
  end if;

  proximo_codigo:=case
    when atual.codigo_etapa='ADM-001' and p_resultado='irregular' then 'ADM-002'
    when atual.codigo_etapa='ADM-001' and p_resultado='contrato_ausente' then null
    when atual.codigo_etapa='ADM-001' then 'ADM-003'
    when atual.codigo_etapa='ADM-002' then 'ADM-001'
    else etapa.proxima_etapa_codigo end;

  perform set_config('celios.conclusao_esteira','1',true);
  update public.tarefas set status='concluida',concluida_em=now(),concluida_por_email=lower(coalesce(auth.jwt()->>'email','')),
    evidencia_url=coalesce(nullif(trim(coalesce(p_evidencia_url,'')),''),evidencia_url),resultado_etapa=p_resultado,updated_at=now()
  where id=atual.id returning * into atual;

  insert into public.alertas_esteira(instancia_esteira_id,tarefa_id,funcionaria_id,tipo,mensagem,destinada_supervisor)
  values(atual.instancia_esteira_id,atual.id,atual.funcionaria_id,'concluida','Etapa administrativa concluida.',true)
  on conflict do nothing;

  if atual.codigo_etapa='ADM-001' and p_resultado='contrato_ausente' then
    subinstancia:=public.criar_subprocesso_esteira_interno(atual.instancia_esteira_id,
      'SUBPROCESSO - SEGUNDA VIA DO CONTRATO',atual.codigo_etapa,atual.funcionaria_id);
  elsif atual.codigo_etapa='ADM-019' then
    if p_resultado='resolvido' then
      update public.instancias_esteira set status='concluida',concluida_em=now(),updated_at=now() where id=atual.instancia_esteira_id;
    elsif p_resultado in ('laudo','preparacao_processual') then
      subinstancia:=public.criar_subprocesso_esteira_interno(atual.instancia_esteira_id,
        case when p_resultado='laudo' then 'SUBPROCESSO - LAUDO' else 'SUBPROCESSO - PREPARACAO PROCESSUAL' end,
        atual.codigo_etapa,atual.funcionaria_id);
    end if;
  elsif proximo_codigo is not null then
    select * into proxima from public.tarefas
    where instancia_esteira_id=atual.instancia_esteira_id and codigo_etapa=proximo_codigo for update;
    update public.tarefas set status='nova',funcionaria_id=coalesce(proxima.funcionaria_id,atual.funcionaria_id),
      data_limite=current_date+(select prazo_padrao_dias from public.modelos_etapas where id=proxima.etapa_modelo_id),
      liberada_em=now(),bloqueada_em=null,motivo_bloqueio=null,exibir_tv=true,updated_at=now()
    where id=proxima.id returning * into proxima;
    insert into public.alertas_esteira(instancia_esteira_id,tarefa_id,funcionaria_id,tipo,mensagem)
    values(proxima.instancia_esteira_id,proxima.id,proxima.funcionaria_id,'liberada','Nova etapa administrativa liberada.')
    on conflict do nothing;
  end if;
  return jsonb_build_object('tarefa_concluida',to_jsonb(atual),'proxima_tarefa',to_jsonb(proxima));
end $$;

create or replace function public.gerenciar_instancia_esteira_supervisor(
  p_instancia_id bigint, p_acao text, p_justificativa text
) returns public.instancias_esteira
language plpgsql security definer set search_path=public as $$
declare registro public.instancias_esteira;
begin
  if not public.usuario_e_admin() then raise exception 'Acesso restrito ao supervisor.'; end if;
  if p_acao not in ('cancelar','arquivar') then raise exception 'Acao invalida.'; end if;
  if nullif(trim(coalesce(p_justificativa,'')),'') is null then raise exception 'Justificativa obrigatoria.'; end if;
  update public.instancias_esteira set status=case when p_acao='cancelar' then 'cancelada' else 'arquivada' end,
    cancelada_em=case when p_acao='cancelar' then now() else cancelada_em end,
    motivo_cancelamento=p_justificativa,updated_at=now()
  where id=p_instancia_id and status='ativa' returning * into registro;
  if registro.id is null then raise exception 'Esteira ativa nao encontrada.'; end if;
  update public.tarefas set status=case when p_acao='cancelar' then 'cancelada' else 'arquivada' end,
    exibir_tv=false,updated_at=now()
  where instancia_esteira_id=p_instancia_id and status not in ('concluida','cancelada','arquivada');
  insert into public.esteiras_eventos(instancia_esteira_id,tipo,descricao)
  values(registro.id,'esteira_'||p_acao,p_justificativa);
  return registro;
end $$;

-- Operacoes sensiveis ficam separadas para a futura interface do supervisor.
create or replace function public.gerenciar_tarefa_esteira_supervisor(
  p_tarefa_id bigint, p_acao text, p_funcionaria_id bigint default null, p_justificativa text default null
) returns public.tarefas
language plpgsql security definer set search_path=public as $$
declare registro public.tarefas;
begin
  if not public.usuario_e_admin() then raise exception 'Acesso restrito ao supervisor.'; end if;
  if p_acao not in ('transferir','dispensar','pular','reabrir') then raise exception 'Acao invalida.'; end if;
  if p_acao in ('dispensar','pular','reabrir') and nullif(trim(coalesce(p_justificativa,'')),'') is null then raise exception 'Justificativa obrigatoria.'; end if;
  if p_acao in ('dispensar','pular') then
    perform public.concluir_tarefa_e_liberar_proxima(p_tarefa_id,null,'nao_se_aplica');
    update public.tarefas set apontamento=concat_ws(E'\n',nullif(apontamento,''),'[Supervisor] '||p_justificativa),updated_at=now()
    where id=p_tarefa_id returning * into registro;
    return registro;
  end if;
  perform set_config('celios.conclusao_esteira','1',true);
  update public.tarefas set
    funcionaria_id=case when p_acao='transferir' then p_funcionaria_id else funcionaria_id end,
    status=case when p_acao='reabrir' then 'nova' else status end,
    apontamento=concat_ws(E'\n',nullif(apontamento,''),'[Supervisor] '||coalesce(p_justificativa,'Transferencia de responsavel.')),
    updated_at=now() where id=p_tarefa_id and origem='esteira' returning * into registro;
  if registro.id is null then raise exception 'Etapa nao encontrada.'; end if;
  return registro;
end $$;

-- Alertas internos calculados sem notificacoes externas ou agendador nesta fase.
create or replace view public.alertas_esteira_calculados
with (security_invoker=true) as
select t.id tarefa_id,t.instancia_esteira_id,t.funcionaria_id,t.titulo,t.data_limite,
  greatest(current_date-t.data_limite,0) dias_atraso,
  case when current_date-t.data_limite>=3 then 'critica'
       when current_date-t.data_limite=2 then 'atrasada_2d'
       when current_date-t.data_limite=1 then 'atrasada_1d'
       else 'no_prazo' end nivel
from public.tarefas t
where t.origem='esteira' and t.status in ('nova','em_andamento','aguardando_cliente','aguardando_banco','aguardando_juridico','impedida','em_revisao')
  and t.data_limite is not null;

