  'Conferir compatibilidade dos enderecos','Anexar documentos no CRM','Revisar pasta',
  'Encaminhar ao Processual','Comunicar o cliente'])
), expandidas as (
  select m.id modelo_id,d.prefixo,u.titulo,u.ordem::integer,
    d.prefixo||'-'||lpad(u.ordem::text,3,'0') codigo
  from dados d join public.modelos_esteira m on m.nome=d.modelo_nome and m.versao=1
  cross join lateral unnest(d.titulos) with ordinality u(titulo,ordem)
)
insert into public.modelos_etapas(modelo_esteira_id,codigo,titulo,descricao,ordem,setor_responsavel,
  prazo_padrao_dias,evidencia_obrigatoria,etapa_anterior_codigo,proxima_etapa_codigo)
select modelo_id,codigo,titulo,titulo,ordem,'Administrativo',
  case when titulo ilike 'Acompanhar%' then 3 else 1 end,
  titulo ilike 'Anexar%' or titulo ilike 'Registrar%' or titulo ilike 'Revisar%',
  lag(codigo) over(partition by modelo_id order by ordem),lead(codigo) over(partition by modelo_id order by ordem)
from expandidas on conflict(modelo_esteira_id,codigo) do nothing;

