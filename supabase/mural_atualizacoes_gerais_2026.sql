-- Mural temporário de atualizações gerais do workspace.
-- Todos os usuários ativos visualizam; os avisos expiram em no máximo 5 horas.
-- Execute depois de status_processual_clientes_2026.sql e grupo_whatsapp_cliente_2026.sql.
-- Script idempotente: pode ser executado novamente com segurança.

begin;

create table if not exists public.atualizacoes_gerais (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('status_processual', 'grupo_whatsapp')),
  titulo text not null,
  mensagem text not null,
  tom text not null default 'info' check (tom in ('info', 'success', 'warning', 'danger')),
  destino text not null check (destino in ('status_processual', 'tarefas')),
  referencia_id bigint,
  created_at timestamptz not null default now(),
  expira_em timestamptz not null default (now() + interval '5 hours'),
  constraint atualizacao_geral_expiracao_check check (
    expira_em > created_at
    and expira_em <= created_at + interval '5 hours'
  )
);

create index if not exists atualizacoes_gerais_expiracao_idx
  on public.atualizacoes_gerais(expira_em, created_at desc);

create or replace function public.publicar_atualizacao_geral(
  p_tipo text,
  p_titulo text,
  p_mensagem text,
  p_tom text,
  p_destino text,
  p_referencia_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.atualizacoes_gerais where expira_em <= now();

  insert into public.atualizacoes_gerais (
    tipo, titulo, mensagem, tom, destino, referencia_id, expira_em
  ) values (
    p_tipo,
    trim(p_titulo),
    trim(p_mensagem),
    p_tom,
    p_destino,
    p_referencia_id,
    now() + interval '5 hours'
  );
end;
$$;

create or replace function public.notificar_mudanca_status_processual()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_cliente text;
  v_titulo text;
  v_mensagem text;
  v_tom text := 'info';
begin
  select c.nome into v_cliente
  from public.clientes c
  where c.id = new.cliente_id;

  if tg_op = 'INSERT' then
    v_titulo := 'Cliente encaminhado ao Processual';
    v_mensagem := coalesce(v_cliente, 'Cliente') || ' entrou na esteira de distribuição judicial.';
  elsif new.status_protocolo = 'protocolado'
    and old.status_protocolo is distinct from new.status_protocolo then
    v_titulo := 'Protocolo disponível';
    v_mensagem := coalesce(v_cliente, 'Cliente') || ' foi protocolado no processo ' || coalesce(new.numero_processo, 'informado no sistema') || '.';
    v_tom := 'success';
  elsif new.status_protocolo = 'pasta_retornou'
    and old.status_protocolo is distinct from new.status_protocolo then
    v_titulo := 'Pasta retornou';
    v_mensagem := 'A pasta processual de ' || coalesce(v_cliente, 'cliente não identificado') || ' retornou e requer atenção.';
    v_tom := 'danger';
  elsif new.status_documentos in ('incorretos', 'irregulares')
    and old.status_documentos is distinct from new.status_documentos then
    v_titulo := 'Documentos irregulares';
    v_mensagem := coalesce(v_cliente, 'Cliente') || ' possui documentos que precisam de correção antes do protocolo.';
    v_tom := 'danger';
  elsif new.status_protocolo = 'em_geracao'
    and old.status_protocolo is distinct from new.status_protocolo then
    v_titulo := 'Protocolo em geração';
    v_mensagem := 'O protocolo de ' || coalesce(v_cliente, 'cliente não identificado') || ' entrou no prazo operacional de 15 dias.';
    v_tom := 'warning';
  elsif old.status_documentos is distinct from new.status_documentos
    or old.status_procuracao is distinct from new.status_procuracao
    or old.status_protocolo is distinct from new.status_protocolo then
    v_titulo := 'Status processual atualizado';
    v_mensagem := 'O andamento de ' || coalesce(v_cliente, 'cliente não identificado') || ' recebeu uma nova atualização.';
  else
    return new;
  end if;

  perform public.publicar_atualizacao_geral(
    'status_processual', v_titulo, v_mensagem, v_tom, 'status_processual', new.id
  );
  return new;
end;
$$;

drop trigger if exists notificar_mudanca_status_processual_trigger
  on public.status_processual_clientes;
create trigger notificar_mudanca_status_processual_trigger
after insert or update of status_documentos, status_procuracao, status_protocolo, numero_processo
on public.status_processual_clientes
for each row
execute function public.notificar_mudanca_status_processual();

create or replace function public.notificar_conclusao_grupo_whatsapp()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.tipo_tarefa_codigo = 'ABRIR_GRUPO_WHATSAPP'
     and new.status = 'concluida'
     and old.status is distinct from new.status then
    perform public.publicar_atualizacao_geral(
      'grupo_whatsapp',
      'Grupo do WhatsApp concluído',
      'O grupo do cliente ' || coalesce(new.nome_cliente, 'não identificado') || ' foi criado e a tarefa foi concluída.',
      'success',
      'tarefas',
      new.id
    );
  end if;
  return new;
end;
$$;

drop trigger if exists notificar_conclusao_grupo_whatsapp_trigger on public.tarefas;
create trigger notificar_conclusao_grupo_whatsapp_trigger
after update of status on public.tarefas
for each row
execute function public.notificar_conclusao_grupo_whatsapp();

create or replace function public.listar_atualizacoes_gerais()
returns table (
  id bigint,
  tipo text,
  titulo text,
  mensagem text,
  tom text,
  destino text,
  referencia_id bigint,
  created_at timestamptz,
  expira_em timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.usuario_pode_visualizar_status_processual() then
    raise exception 'Usuário sem acesso ao mural de atualizações.';
  end if;

  delete from public.atualizacoes_gerais where atualizacoes_gerais.expira_em <= now();

  return query
  select
    a.id, a.tipo, a.titulo, a.mensagem, a.tom, a.destino,
    a.referencia_id, a.created_at, a.expira_em
  from public.atualizacoes_gerais a
  where a.expira_em > now()
  order by a.created_at desc
  limit 12;
end;
$$;

alter table public.atualizacoes_gerais enable row level security;

revoke all on public.atualizacoes_gerais from anon, authenticated;
revoke all on function public.publicar_atualizacao_geral(text,text,text,text,text,bigint) from public;
revoke all on function public.notificar_mudanca_status_processual() from public;
revoke all on function public.notificar_conclusao_grupo_whatsapp() from public;
revoke all on function public.listar_atualizacoes_gerais() from public;

grant execute on function public.listar_atualizacoes_gerais() to authenticated;

commit;

notify pgrst, 'reload schema';

select
  to_regprocedure('public.listar_atualizacoes_gerais()') is not null as mural_instalado,
  count(*) as atualizacoes_ativas
from public.atualizacoes_gerais
where expira_em > now();
