begin;

create table if not exists public.modelos_tarefa (
  id bigint generated by default as identity primary key,
  nome text not null,
  titulo text not null,
  descricao text,
  categoria text not null,
  prioridade text not null default 'normal',
  pontos_tarefa integer not null default 10 check (pontos_tarefa >= 0),
  prazo_dias integer not null default 0 check (prazo_dias >= 0),
  exibir_tv boolean not null default true,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.processos (
  id bigint generated by default as identity primary key,
  numero text not null unique,
  cliente text not null,
  parte_contraria text,
  tribunal text,
  vara text,
  tipo_acao text,
  fase text not null default 'conhecimento',
  status text not null default 'ativo',
  risco text not null default 'medio',
  valor_causa numeric(14,2),
  funcionaria_id bigint references public.funcionarios(id) on delete set null,
  proximo_prazo date,
  observacoes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint processos_status_check check (status in ('ativo', 'suspenso', 'encerrado', 'arquivado')),
  constraint processos_risco_check check (risco in ('baixo', 'medio', 'alto', 'critico'))
);

create table if not exists public.processos_andamentos (
  id bigint generated by default as identity primary key,
  processo_id bigint not null references public.processos(id) on delete cascade,
  tipo text not null default 'andamento',
  descricao text not null,
  data_andamento date not null default current_date,
  prazo date,
  criado_por text,
  created_at timestamptz not null default now()
);

create index if not exists modelos_tarefa_ativo_idx on public.modelos_tarefa (ativo, categoria, nome);
create index if not exists processos_responsavel_status_idx on public.processos (funcionaria_id, status, proximo_prazo);
create index if not exists processos_andamentos_processo_idx on public.processos_andamentos (processo_id, data_andamento desc, id desc);

alter table public.modelos_tarefa enable row level security;
alter table public.processos enable row level security;
alter table public.processos_andamentos enable row level security;

revoke all on public.modelos_tarefa, public.processos, public.processos_andamentos from anon;
grant select on public.modelos_tarefa, public.processos, public.processos_andamentos to authenticated;

drop policy if exists "Equipe consulta modelos ativos" on public.modelos_tarefa;
create policy "Equipe consulta modelos ativos" on public.modelos_tarefa
for select to authenticated using (ativo or public.usuario_e_admin());

drop policy if exists "Equipe consulta processos permitidos" on public.processos;
create policy "Equipe consulta processos permitidos" on public.processos
for select to authenticated using (
  public.usuario_e_admin() or funcionaria_id = public.funcionario_id_autenticado()
);

drop policy if exists "Equipe consulta andamentos permitidos" on public.processos_andamentos;
create policy "Equipe consulta andamentos permitidos" on public.processos_andamentos
for select to authenticated using (
  exists (
    select 1 from public.processos p
    where p.id = processo_id
      and (public.usuario_e_admin() or p.funcionaria_id = public.funcionario_id_autenticado())
  )
);

create or replace function public.salvar_modelo_tarefa_supervisor(
  p_id bigint, p_nome text, p_titulo text, p_descricao text,
  p_categoria text, p_prioridade text, p_pontos integer,
  p_prazo_dias integer, p_exibir_tv boolean, p_ativo boolean
) returns public.modelos_tarefa
language plpgsql security definer set search_path = public as $$
declare registro public.modelos_tarefa;
begin
  if not public.usuario_e_admin() then raise exception 'Acesso restrito ao supervisor.'; end if;
  if nullif(trim(p_nome), '') is null or nullif(trim(p_titulo), '') is null then
    raise exception 'Nome e titulo sao obrigatorios.';
  end if;
  if p_prioridade not in ('normal', 'alta', 'urgente') then raise exception 'Prioridade invalida.'; end if;
  if p_id is null then
    insert into public.modelos_tarefa (nome, titulo, descricao, categoria, prioridade, pontos_tarefa, prazo_dias, exibir_tv, ativo)
    values (trim(p_nome), trim(p_titulo), nullif(trim(coalesce(p_descricao, '')), ''), p_categoria,
      p_prioridade, greatest(coalesce(p_pontos, 0), 0), greatest(coalesce(p_prazo_dias, 0), 0),
      coalesce(p_exibir_tv, true), coalesce(p_ativo, true)) returning * into registro;
  else
    update public.modelos_tarefa set nome=trim(p_nome), titulo=trim(p_titulo),
      descricao=nullif(trim(coalesce(p_descricao, '')), ''), categoria=p_categoria,
      prioridade=p_prioridade, pontos_tarefa=greatest(coalesce(p_pontos, 0), 0),
      prazo_dias=greatest(coalesce(p_prazo_dias, 0), 0), exibir_tv=coalesce(p_exibir_tv, true),
      ativo=coalesce(p_ativo, true), updated_at=now()
    where id=p_id returning * into registro;
  end if;
  if registro.id is null then raise exception 'Modelo nao encontrado.'; end if;
  return registro;
end $$;

create or replace function public.aplicar_modelo_tarefa_supervisor(p_modelo_id bigint, p_funcionaria_id bigint)
returns public.tarefas
language plpgsql security definer set search_path = public as $$
declare modelo public.modelos_tarefa; tarefa public.tarefas;
begin
  if not public.usuario_e_admin() then raise exception 'Acesso restrito ao supervisor.'; end if;
  select * into modelo from public.modelos_tarefa where id=p_modelo_id and ativo=true;
  if modelo.id is null then raise exception 'Modelo ativo nao encontrado.'; end if;
  if not exists (select 1 from public.funcionarios where id=p_funcionaria_id and ativo=true) then
    raise exception 'Responsavel ativa nao encontrada.';
  end if;
  insert into public.tarefas (titulo, descricao, funcionaria_id, pontos_tarefa, data_limite,
    status, prioridade, categoria, exibir_tv, tarefa_manual, updated_at)
  values (modelo.titulo, modelo.descricao, p_funcionaria_id, modelo.pontos_tarefa,
    case when modelo.prazo_dias > 0 then current_date + modelo.prazo_dias else null end,
    'nova', modelo.prioridade, modelo.categoria, modelo.exibir_tv, false, now())
  returning * into tarefa;
  return tarefa;
end $$;

create or replace function public.salvar_processo_supervisor(
  p_id bigint, p_numero text, p_cliente text, p_parte_contraria text,
  p_tribunal text, p_vara text, p_tipo_acao text, p_fase text,
  p_status text, p_risco text, p_valor_causa numeric,
  p_funcionaria_id bigint, p_proximo_prazo date, p_observacoes text
) returns public.processos
language plpgsql security definer set search_path = public as $$
declare registro public.processos;
begin
  if not public.usuario_e_admin() then raise exception 'Acesso restrito ao supervisor.'; end if;
  if nullif(trim(p_numero), '') is null or nullif(trim(p_cliente), '') is null then
    raise exception 'Numero e cliente sao obrigatorios.';
  end if;
  if p_status not in ('ativo','suspenso','encerrado','arquivado') then raise exception 'Status invalido.'; end if;
  if p_risco not in ('baixo','medio','alto','critico') then raise exception 'Risco invalido.'; end if;
  if p_id is null then
    insert into public.processos (numero, cliente, parte_contraria, tribunal, vara, tipo_acao, fase,
      status, risco, valor_causa, funcionaria_id, proximo_prazo, observacoes)
    values (trim(p_numero), trim(p_cliente), nullif(trim(coalesce(p_parte_contraria,'')),''),
      nullif(trim(coalesce(p_tribunal,'')),''), nullif(trim(coalesce(p_vara,'')),''),
      nullif(trim(coalesce(p_tipo_acao,'')),''), coalesce(nullif(trim(p_fase),''),'conhecimento'),
      p_status, p_risco, p_valor_causa, p_funcionaria_id, p_proximo_prazo,
      nullif(trim(coalesce(p_observacoes,'')),'')) returning * into registro;
  else
    update public.processos set numero=trim(p_numero), cliente=trim(p_cliente),
      parte_contraria=nullif(trim(coalesce(p_parte_contraria,'')),''), tribunal=nullif(trim(coalesce(p_tribunal,'')),''),
      vara=nullif(trim(coalesce(p_vara,'')),''), tipo_acao=nullif(trim(coalesce(p_tipo_acao,'')),''),
      fase=coalesce(nullif(trim(p_fase),''),'conhecimento'), status=p_status, risco=p_risco,
      valor_causa=p_valor_causa, funcionaria_id=p_funcionaria_id, proximo_prazo=p_proximo_prazo,
      observacoes=nullif(trim(coalesce(p_observacoes,'')),''), updated_at=now()
    where id=p_id returning * into registro;
  end if;
  if registro.id is null then raise exception 'Processo nao encontrado.'; end if;
  return registro;
end $$;

create or replace function public.registrar_andamento_supervisor(
  p_processo_id bigint, p_tipo text, p_descricao text, p_data date, p_prazo date
) returns public.processos_andamentos
language plpgsql security definer set search_path = public as $$
declare registro public.processos_andamentos;
begin
  if not public.usuario_e_admin() then raise exception 'Acesso restrito ao supervisor.'; end if;
  if nullif(trim(p_descricao),'') is null then raise exception 'Descricao obrigatoria.'; end if;
  insert into public.processos_andamentos (processo_id, tipo, descricao, data_andamento, prazo, criado_por)
  values (p_processo_id, coalesce(nullif(trim(p_tipo),''),'andamento'), trim(p_descricao),
    coalesce(p_data,current_date), p_prazo, auth.jwt() ->> 'email') returning * into registro;
  if p_prazo is not null then update public.processos set proximo_prazo=p_prazo, updated_at=now() where id=p_processo_id; end if;
  return registro;
end $$;

revoke all on function public.salvar_modelo_tarefa_supervisor(bigint,text,text,text,text,text,integer,integer,boolean,boolean) from public;
grant execute on function public.salvar_modelo_tarefa_supervisor(bigint,text,text,text,text,text,integer,integer,boolean,boolean) to authenticated;
revoke all on function public.aplicar_modelo_tarefa_supervisor(bigint,bigint) from public;
grant execute on function public.aplicar_modelo_tarefa_supervisor(bigint,bigint) to authenticated;
revoke all on function public.salvar_processo_supervisor(bigint,text,text,text,text,text,text,text,text,text,numeric,bigint,date,text) from public;
grant execute on function public.salvar_processo_supervisor(bigint,text,text,text,text,text,text,text,text,text,numeric,bigint,date,text) to authenticated;
revoke all on function public.registrar_andamento_supervisor(bigint,text,text,date,date) from public;
grant execute on function public.registrar_andamento_supervisor(bigint,text,text,date,date) to authenticated;

notify pgrst, 'reload schema';
commit;
