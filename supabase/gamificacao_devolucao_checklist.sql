-- Nenhum UPDATE direto, nem mesmo do supervisor, pode fabricar uma devolucao
-- sem o registro atomico do motivo e do comentario.
create or replace function public.proteger_devolucao_sem_justificativa()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'devolvida'
     and new.status is distinct from old.status
     and coalesce(
       current_setting('platino.devolucao_validada', true),
       '0'
     ) <> '1' then
    raise exception
      'Use a acao Devolver Tarefa e informe motivo e comentario.';
  end if;
  return new;
end;
$$;

drop trigger if exists proteger_devolucao_sem_justificativa
on public.tarefas;
create trigger proteger_devolucao_sem_justificativa
before update of status on public.tarefas
for each row
execute function public.proteger_devolucao_sem_justificativa();

-- Preserva a protecao das tarefas da funcionaria e autoriza DEVOLVIDA
-- exclusivamente durante a transacao validada pela funcao devolver_tarefa.
create or replace function public.proteger_edicao_tarefa_funcionaria()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'devolvida'
     and new.status is distinct from old.status
     and coalesce(
       current_setting('platino.devolucao_validada', true),
       '0'
     ) <> '1' then
    raise exception 'A justificativa da devolucao e obrigatoria.';
  end if;

  if public.usuario_e_admin() then
    return new;
  end if;

  if new.funcionaria_id is distinct from old.funcionaria_id
     or new.exibir_tv is distinct from old.exibir_tv then
    raise exception
      'A colaboradora nao pode alterar responsavel ou visibilidade.';
  end if;

  if old.origem = 'esteira'
     and new.status = 'concluida'
     and coalesce(
       current_setting('celios.conclusao_esteira', true),
       '0'
     ) <> '1' then
    raise exception
      'Etapas de esteira devem ser concluidas pelo fluxo transacional.';
  end if;

  if new.status is distinct from old.status then
    if new.status = 'devolvida'
       and coalesce(
         current_setting('platino.devolucao_validada', true),
         '0'
       ) = '1' then
      return new;
    end if;

    if new.status <> 'concluida' then
      raise exception 'Alteracao de status nao autorizada.';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists proteger_edicao_tarefa_funcionaria
on public.tarefas;
create trigger proteger_edicao_tarefa_funcionaria
before update on public.tarefas
for each row
execute function public.proteger_edicao_tarefa_funcionaria();

create or replace function public.devolver_tarefa(
  p_tarefa_id bigint,
  p_motivo text,
  p_comentario text
)
returns public.tarefas
language plpgsql
security definer
set search_path = public
as $$
declare
  tarefa_atual public.tarefas;
  tarefa_devolvida public.tarefas;
  usuario_id bigint := public.funcionario_id_autenticado();
  email_autor text := lower(trim(coalesce(auth.jwt() ->> 'email', '')));
  comentario_normalizado text := trim(coalesce(p_comentario, ''));
begin
  if p_motivo not in (
    'Dados incorretos',
    'Documento faltante',
    'Documento ilegível',
    'Informação divergente',
    'Assinatura ausente',
    'Outro'
  ) then
    raise exception 'Selecione um motivo valido para a devolucao.';
  end if;

  if char_length(comentario_normalizado) < 10 then
    raise exception
      'O comentario explicativo deve possuir pelo menos 10 caracteres.';
  end if;

  select *
  into tarefa_atual
  from public.tarefas
  where id = p_tarefa_id
  for update;

  if tarefa_atual.id is null then
    raise exception 'Tarefa nao encontrada.';
  end if;

  if not public.usuario_e_admin()
     and tarefa_atual.funcionaria_id is distinct from usuario_id then
    raise exception 'Esta tarefa nao esta atribuida ao usuario autenticado.';
  end if;

  if tarefa_atual.status not in (
    'pendente',
    'nova',
    'em_andamento',
    'aguardando_cliente',
    'aguardando_banco',
    'aguardando_juridico',
    'aguardando_judiciario',
    'impedida',
    'em_revisao'
  ) then
    raise exception 'A tarefa nao esta disponivel para devolucao.';
  end if;

  insert into public.tarefas_comentarios (
    tarefa_id,
    funcionaria_id,
    autor_email,
    texto,
    motivo_devolucao,
    is_return_justification
  )
  values (
    tarefa_atual.id,
    usuario_id,
    email_autor,
    comentario_normalizado,
    p_motivo,
    true
  );

  perform set_config('platino.devolucao_validada', '1', true);

  update public.tarefas
  set
    status = 'devolvida',
    motivo_devolucao = p_motivo,
    comentario_devolucao = comentario_normalizado,
    devolvida_em = now(),
    updated_at = now()
  where id = tarefa_atual.id
  returning * into tarefa_devolvida;

  return tarefa_devolvida;
end;
$$;

create or replace function public.salvar_checklist_documentos(
  p_tarefa_id bigint,
  p_documentos jsonb
)
returns public.tarefas
language plpgsql
security definer
set search_path = public
as $$
declare
  tarefa_atual public.tarefas;
  tarefa_atualizada public.tarefas;
  usuario_id bigint := public.funcionario_id_autenticado();
  documentos_normalizados jsonb;
  completo boolean;
begin
  select *
  into tarefa_atual
  from public.tarefas
  where id = p_tarefa_id
  for update;

  if tarefa_atual.id is null then
    raise exception 'Tarefa nao encontrada.';
  end if;

  if not public.usuario_e_admin()
     and tarefa_atual.funcionaria_id is distinct from usuario_id then
    raise exception 'Esta tarefa nao esta atribuida ao usuario autenticado.';
  end if;

  if tarefa_atual.status in (
    'devolvida',
    'concluida',
    'cancelada',
    'arquivada'
  ) then
    raise exception 'O checklist nao pode ser alterado neste status.';
  end if;

  if not (
    upper(coalesce(tarefa_atual.codigo_etapa, '')) = 'ADM-007'
    or lower(coalesce(tarefa_atual.titulo, '')) like '%5 documentos iniciais%'
    or lower(coalesce(tarefa_atual.titulo, '')) like '%cinco documentos iniciais%'
    or lower(coalesce(tarefa_atual.titulo, '')) like '%conferir documentos iniciais%'
  ) then
    raise exception 'Esta tarefa nao pertence ao check-in documental.';
  end if;

  documentos_normalizados := jsonb_build_object(
    'contrato_assinado',
      coalesce((p_documentos ->> 'contrato_assinado')::boolean, false),
    'documento_identificacao',
      coalesce((p_documentos ->> 'documento_identificacao')::boolean, false),
    'cpf',
      coalesce((p_documentos ->> 'cpf')::boolean, false),
    'comprovante_residencia',
      coalesce((p_documentos ->> 'comprovante_residencia')::boolean, false),
    'comprovante_renda',
      coalesce((p_documentos ->> 'comprovante_renda')::boolean, false)
  );

  completo := documentos_normalizados @> '{
    "contrato_assinado": true,
    "documento_identificacao": true,
    "cpf": true,
    "comprovante_residencia": true,
    "comprovante_renda": true
  }'::jsonb;

  update public.tarefas
  set
    checklist_documentos = documentos_normalizados,
    checklist_documentos_completo = completo,
    updated_at = now()
  where id = tarefa_atual.id
  returning * into tarefa_atualizada;

  return tarefa_atualizada;
end;
$$;

create or replace function public.bloquear_avanco_sem_documentos()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'concluida'
     and new.status is distinct from old.status
     and (
       upper(coalesce(new.codigo_etapa, '')) = 'ADM-007'
       or lower(coalesce(new.titulo, '')) like '%5 documentos iniciais%'
       or lower(coalesce(new.titulo, '')) like '%cinco documentos iniciais%'
       or lower(coalesce(new.titulo, '')) like '%conferir documentos iniciais%'
     )
     and new.checklist_documentos_completo is not true then
    raise exception
      'Os 5 documentos iniciais devem ser confirmados antes do avanco.';
  end if;
  return new;
end;
$$;

drop trigger if exists bloquear_avanco_sem_documentos on public.tarefas;
create trigger bloquear_avanco_sem_documentos
before update of status on public.tarefas
for each row
execute function public.bloquear_avanco_sem_documentos();

create or replace function public.registrar_perda_prazo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' and new.status = 'concluida' then
    new.prazo_perdido :=
      new.data_limite is not null
      and coalesce(new.concluida_em, now())::date > new.data_limite;
  elsif tg_op = 'UPDATE'
        and new.status = 'concluida'
        and new.status is distinct from old.status then
    new.prazo_perdido :=
      new.data_limite is not null
      and coalesce(new.concluida_em, now())::date > new.data_limite;
  end if;
  return new;
end;
$$;

drop trigger if exists registrar_perda_prazo on public.tarefas;
create trigger registrar_perda_prazo
before insert or update of status, data_limite, concluida_em
on public.tarefas
for each row
execute function public.registrar_perda_prazo();

