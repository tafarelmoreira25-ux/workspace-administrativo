-- Painel compartilhado de Status Processual.
-- Todos os usuários ativos podem consultar; somente o Administrativo edita.
-- Execute depois de configurar_sistema.sql e google_drive_clientes_historicos_2026.sql.
-- Script idempotente: pode ser executado novamente com segurança.

begin;

create table if not exists public.status_processual_clientes (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null unique references public.clientes(id) on delete restrict,
  status_documentos text not null default 'pendente_conferencia'
    check (status_documentos in ('pendente_conferencia', 'corretos', 'incorretos', 'irregulares')),
  status_procuracao text not null default 'pendente'
    check (status_procuracao in ('pendente', 'encaminhada', 'pendente_assinatura', 'nao_aplicavel')),
  status_protocolo text not null default 'pendente'
    check (status_protocolo in ('pendente', 'em_geracao', 'protocolado', 'pasta_retornou')),
  numero_processo text,
  protocolo_iniciado_em timestamptz,
  prazo_protocolo date,
  observacao text,
  criado_por_email text not null default lower(coalesce(auth.jwt() ->> 'email', '')),
  atualizado_por_email text not null default lower(coalesce(auth.jwt() ->> 'email', '')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint status_processual_numero_check check (
    status_protocolo <> 'protocolado'
    or nullif(trim(coalesce(numero_processo, '')), '') is not null
  )
);

create table if not exists public.status_processual_historico (
  id bigint generated by default as identity primary key,
  status_processual_id bigint not null references public.status_processual_clientes(id) on delete cascade,
  status_documentos_anterior text,
  status_documentos_novo text not null,
  status_procuracao_anterior text,
  status_procuracao_novo text not null,
  status_protocolo_anterior text,
  status_protocolo_novo text not null,
  numero_processo text,
  observacao text,
  autor_email text not null,
  created_at timestamptz not null default now()
);

create index if not exists status_processual_protocolo_idx
  on public.status_processual_clientes(status_protocolo, prazo_protocolo, updated_at desc);
create index if not exists status_processual_historico_registro_idx
  on public.status_processual_historico(status_processual_id, created_at desc);

create or replace function public.usuario_pode_visualizar_status_processual()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    lower(trim(coalesce(auth.jwt() ->> 'email', ''))) in (
      'tafarel@platino.com',
      'tafa@adm.com'
    )
    or exists (
      select 1
      from public.funcionarios f
      where lower(trim(f.email)) = lower(trim(coalesce(auth.jwt() ->> 'email', '')))
        and f.ativo is not false
    );
$$;

create or replace function public.usuario_pode_editar_status_processual()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    lower(trim(coalesce(auth.jwt() ->> 'email', ''))) in (
      'tafarel@platino.com',
      'tafa@adm.com'
    )
    or exists (
      select 1
      from public.funcionarios f
      where lower(trim(f.email)) = lower(trim(coalesce(auth.jwt() ->> 'email', '')))
        and f.ativo is not false
        and (
          lower(coalesce(f.setor, '')) like '%administr%'
          or lower(trim(coalesce(f.setor, ''))) = 'adm'
          or lower(coalesce(f.cargo, '')) like '%administr%'
        )
    );
$$;

create or replace function public.listar_status_processual()
returns table (
  id bigint,
  cliente_id bigint,
  nome_cliente text,
  status_documentos text,
  status_procuracao text,
  status_protocolo text,
  numero_processo text,
  protocolo_iniciado_em timestamptz,
  prazo_protocolo date,
  observacao text,
  atualizado_por_email text,
  created_at timestamptz,
  updated_at timestamptz,
  pasta_drive_url text,
  pasta_drive_nome text,
  drive_status text,
  drive_path text
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.usuario_pode_visualizar_status_processual() then
    raise exception 'Usuário sem acesso ao Status Processual.';
  end if;

  return query
  select
    s.id,
    s.cliente_id,
    c.nome,
    s.status_documentos,
    s.status_procuracao,
    s.status_protocolo,
    s.numero_processo,
    s.protocolo_iniciado_em,
    s.prazo_protocolo,
    s.observacao,
    s.atualizado_por_email,
    s.created_at,
    s.updated_at,
    c.pasta_drive_url,
    c.pasta_drive_nome,
    c.drive_status,
    c.drive_path
  from public.status_processual_clientes s
  join public.clientes c on c.id = s.cliente_id
  order by
    case s.status_protocolo
      when 'pasta_retornou' then 1
      when 'pendente' then 2
      when 'em_geracao' then 3
      else 4
    end,
    s.prazo_protocolo nulls last,
    s.updated_at desc;
end;
$$;

create or replace function public.salvar_status_processual(
  p_registro_id bigint,
  p_cliente_id bigint,
  p_status_documentos text,
  p_status_procuracao text,
  p_status_protocolo text,
  p_numero_processo text,
  p_observacao text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_registro public.status_processual_clientes;
  v_anterior public.status_processual_clientes;
  v_email text := lower(trim(coalesce(auth.jwt() ->> 'email', '')));
  v_inicio timestamptz;
  v_prazo date;
begin
  if not public.usuario_pode_editar_status_processual() then
    raise exception 'Somente o departamento Administrativo pode alterar o Status Processual.';
  end if;

  if not exists (
    select 1 from public.clientes c where c.id = p_cliente_id
  ) then
    raise exception 'Selecione um cliente válido do Google Drive.';
  end if;

  if p_status_documentos not in ('pendente_conferencia', 'corretos', 'incorretos', 'irregulares') then
    raise exception 'Status dos documentos inválido.';
  end if;
  if p_status_procuracao not in ('pendente', 'encaminhada', 'pendente_assinatura', 'nao_aplicavel') then
    raise exception 'Status da procuração inválido.';
  end if;
  if p_status_protocolo not in ('pendente', 'em_geracao', 'protocolado', 'pasta_retornou') then
    raise exception 'Status do protocolo inválido.';
  end if;
  if p_status_protocolo = 'protocolado'
     and nullif(trim(coalesce(p_numero_processo, '')), '') is null then
    raise exception 'Informe o número do processo para marcar o cliente como Protocolado.';
  end if;

  if p_registro_id is not null then
    select s.* into v_anterior
    from public.status_processual_clientes s
    where s.id = p_registro_id
    for update;
  else
    select s.* into v_anterior
    from public.status_processual_clientes s
    where s.cliente_id = p_cliente_id
    for update;
  end if;

  if p_status_protocolo = 'em_geracao' then
    v_inicio := case
      when v_anterior.id is not null and v_anterior.status_protocolo = 'em_geracao'
        then coalesce(v_anterior.protocolo_iniciado_em, now())
      else now()
    end;
    v_prazo := case
      when v_anterior.id is not null and v_anterior.status_protocolo = 'em_geracao'
        then coalesce(v_anterior.prazo_protocolo, (v_inicio at time zone 'America/Sao_Paulo')::date + 15)
      else (v_inicio at time zone 'America/Sao_Paulo')::date + 15
    end;
  else
    v_inicio := v_anterior.protocolo_iniciado_em;
    v_prazo := v_anterior.prazo_protocolo;
  end if;

  if v_anterior.id is null then
    insert into public.status_processual_clientes (
      cliente_id,
      status_documentos,
      status_procuracao,
      status_protocolo,
      numero_processo,
      protocolo_iniciado_em,
      prazo_protocolo,
      observacao,
      criado_por_email,
      atualizado_por_email
    ) values (
      p_cliente_id,
      p_status_documentos,
      p_status_procuracao,
      p_status_protocolo,
      case when p_status_protocolo = 'protocolado' then trim(p_numero_processo) end,
      v_inicio,
      v_prazo,
      nullif(trim(coalesce(p_observacao, '')), ''),
      v_email,
      v_email
    )
    returning * into v_registro;
  else
    update public.status_processual_clientes
    set cliente_id = p_cliente_id,
        status_documentos = p_status_documentos,
        status_procuracao = p_status_procuracao,
        status_protocolo = p_status_protocolo,
        numero_processo = case when p_status_protocolo = 'protocolado' then trim(p_numero_processo) end,
        protocolo_iniciado_em = v_inicio,
        prazo_protocolo = v_prazo,
        observacao = nullif(trim(coalesce(p_observacao, '')), ''),
        atualizado_por_email = v_email,
        updated_at = now()
    where id = v_anterior.id
    returning * into v_registro;
  end if;

  insert into public.status_processual_historico (
    status_processual_id,
    status_documentos_anterior,
    status_documentos_novo,
    status_procuracao_anterior,
    status_procuracao_novo,
    status_protocolo_anterior,
    status_protocolo_novo,
    numero_processo,
    observacao,
    autor_email
  ) values (
    v_registro.id,
    v_anterior.status_documentos,
    v_registro.status_documentos,
    v_anterior.status_procuracao,
    v_registro.status_procuracao,
    v_anterior.status_protocolo,
    v_registro.status_protocolo,
    v_registro.numero_processo,
    v_registro.observacao,
    v_email
  );

  return v_registro.id;
end;
$$;

alter table public.status_processual_clientes enable row level security;
alter table public.status_processual_historico enable row level security;

revoke all on public.status_processual_clientes, public.status_processual_historico from anon, authenticated;
revoke all on function public.usuario_pode_visualizar_status_processual() from public;
revoke all on function public.usuario_pode_editar_status_processual() from public;
revoke all on function public.listar_status_processual() from public;
revoke all on function public.salvar_status_processual(bigint,bigint,text,text,text,text,text) from public;

grant execute on function public.usuario_pode_visualizar_status_processual() to authenticated;
grant execute on function public.usuario_pode_editar_status_processual() to authenticated;
grant execute on function public.listar_status_processual() to authenticated;
grant execute on function public.salvar_status_processual(bigint,bigint,text,text,text,text,text) to authenticated;

commit;

notify pgrst, 'reload schema';

select
  to_regprocedure('public.listar_status_processual()') is not null as consulta_instalada,
  to_regprocedure('public.salvar_status_processual(bigint,bigint,text,text,text,text,text)') is not null as edicao_instalada;
