-- CELIOS - CORRECAO DO MODULO PROCESSUAL
-- Preserva as tabelas processos/processos_andamentos existentes, mas a nova interface nao as utiliza.
-- Execute uma vez depois de modelos_processual.sql.

begin;

create table if not exists public.relatorios_processuais (
  id bigint generated by default as identity primary key,
  codigo text unique,
  ano_codigo integer,
  sequencia integer,
  cliente text,
  numero_processo text,
  data_consulta text,
  responsavel text,
  resumo_original text,
  dados jsonb not null default '{}'::jsonb,
  anexos jsonb not null default '[]'::jsonb,
  pdf_url text,
  situacao text not null default 'rascunho' check (situacao in ('rascunho','gerado')),
  criado_por text not null default lower(coalesce(auth.jwt() ->> 'email', '')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  gerado_em timestamptz,
  unique (ano_codigo, sequencia)
);

create index if not exists relatorios_processuais_situacao_idx
on public.relatorios_processuais (situacao, created_at desc);

alter table public.relatorios_processuais enable row level security;
revoke all on public.relatorios_processuais from anon;
grant select on public.relatorios_processuais to authenticated;

drop policy if exists "Supervisor consulta relatorios processuais" on public.relatorios_processuais;
create policy "Supervisor consulta relatorios processuais"
on public.relatorios_processuais for select to authenticated
using (public.usuario_e_admin());

create or replace function public.salvar_rascunho_processual(
  p_id bigint,
  p_resumo_original text,
  p_dados jsonb,
  p_anexos jsonb
) returns public.relatorios_processuais
language plpgsql security definer set search_path = public as $$
declare registro public.relatorios_processuais;
begin
  if not public.usuario_e_admin() then raise exception 'Acesso restrito ao supervisor.'; end if;
  if p_id is null then
    insert into public.relatorios_processuais (
      resumo_original, dados, anexos, cliente, numero_processo,
      data_consulta, responsavel, situacao
    ) values (
      p_resumo_original, coalesce(p_dados,'{}'::jsonb), coalesce(p_anexos,'[]'::jsonb),
      nullif(trim(p_dados->>'cliente_autor'),''), nullif(trim(p_dados->>'numero_processo'),''),
      nullif(trim(p_dados->>'data_consulta'),''), nullif(trim(p_dados->>'responsavel'),''), 'rascunho'
    ) returning * into registro;
  else
    update public.relatorios_processuais set
      resumo_original=p_resumo_original, dados=coalesce(p_dados,'{}'::jsonb),
      anexos=coalesce(p_anexos,'[]'::jsonb), cliente=nullif(trim(p_dados->>'cliente_autor'),''),
      numero_processo=nullif(trim(p_dados->>'numero_processo'),''),
      data_consulta=nullif(trim(p_dados->>'data_consulta'),''),
      responsavel=nullif(trim(p_dados->>'responsavel'),''), updated_at=now()
    where id=p_id and situacao='rascunho' returning * into registro;
  end if;
  if registro.id is null then raise exception 'Rascunho nao encontrado ou ja confirmado.'; end if;
  return registro;
end $$;

create or replace function public.confirmar_relatorio_processual(
  p_id bigint,
  p_cliente text,
  p_numero_processo text,
  p_data_consulta text,
  p_responsavel text
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  registro public.relatorios_processuais;
  ano integer := extract(year from current_date)::integer;
  proxima integer;
  novo_codigo text;
begin
  if not public.usuario_e_admin() then raise exception 'Acesso restrito ao supervisor.'; end if;
  if nullif(trim(p_cliente),'') is null or nullif(trim(p_numero_processo),'') is null then
    raise exception 'Cliente e numero do processo sao obrigatorios.';
  end if;

  if p_id is not null then
    select * into registro from public.relatorios_processuais where id=p_id for update;
    if registro.situacao='gerado' then
      return jsonb_build_object('id',registro.id,'codigo',registro.codigo);
    end if;
  end if;

  perform pg_advisory_xact_lock(82471, ano);
  select coalesce(max(sequencia),0)+1 into proxima
  from public.relatorios_processuais where ano_codigo=ano;
  novo_codigo := format('RLPROC-%s-%s',ano,lpad(proxima::text,6,'0'));

  if p_id is null then
    insert into public.relatorios_processuais (codigo,ano_codigo,sequencia,cliente,numero_processo,data_consulta,responsavel,situacao,gerado_em)
    values (novo_codigo,ano,proxima,trim(p_cliente),trim(p_numero_processo),p_data_consulta,p_responsavel,'gerado',now())
    returning * into registro;
  else
    update public.relatorios_processuais set codigo=novo_codigo, ano_codigo=ano,
      sequencia=proxima, cliente=trim(p_cliente), numero_processo=trim(p_numero_processo),
      data_consulta=p_data_consulta, responsavel=p_responsavel, situacao='gerado',
      gerado_em=now(), updated_at=now()
    where id=p_id returning * into registro;
  end if;
  return jsonb_build_object('id',registro.id,'codigo',registro.codigo);
end $$;

revoke all on function public.salvar_rascunho_processual(bigint,text,jsonb,jsonb) from public;
grant execute on function public.salvar_rascunho_processual(bigint,text,jsonb,jsonb) to authenticated;
revoke all on function public.confirmar_relatorio_processual(bigint,text,text,text,text) from public;
grant execute on function public.confirmar_relatorio_processual(bigint,text,text,text,text) to authenticated;

notify pgrst, 'reload schema';
commit;
