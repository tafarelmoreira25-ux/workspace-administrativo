export function normalizarBuscaTreinamento(valor = "") {
  return String(valor)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}

export function filtrarTreinamentos({ busca = "", equipe = "Todas" } = {}) {
  const termo = normalizarBuscaTreinamento(busca.trim());
  return TREINAMENTOS_OPERACIONAIS.filter((treinamento) => {
    const equipeCompativel = equipe === "Todas" || treinamento.equipe === "Todas" || treinamento.equipe === equipe;
    if (!equipeCompativel) return false;
    if (!termo) return true;
    return normalizarBuscaTreinamento([
      treinamento.titulo,
      treinamento.descricao,
      treinamento.tipo,
      treinamento.equipe,
      ...treinamento.categorias,
      ...treinamento.palavras,
    ].join(" ")).includes(termo);
  });
}
